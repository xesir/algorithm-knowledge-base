create extension if not exists pgcrypto with schema extensions;

-- ---------- 通用 updated_at ----------
create or replace function public.set_updated_at()
returns trigger
language plpgsql
as $$
begin
    new.updated_at = now();
    return new;
end;
$$;

-- ---------- 用户资料 ----------
create table if not exists public.profiles (
    id uuid primary key references auth.users(id) on delete cascade,
    nickname text not null,
    contact text,
    role text not null default 'user' check (role in ('user', 'admin')),
    status text not null default 'pending' check (status in ('pending', 'active', 'rejected')),
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

-- 兼容已建过 profiles 的项目：补充 QQ / 洛谷 / CF 绑定字段（默认留空）
alter table public.profiles add column if not exists qq text;
alter table public.profiles add column if not exists luogu text;
alter table public.profiles add column if not exists cf text;

drop trigger if exists trg_profiles_updated_at on public.profiles;
create trigger trg_profiles_updated_at
before update on public.profiles
for each row execute function public.set_updated_at();

-- ---------- 工单 ----------
create table if not exists public.tickets (
    id bigint generated by default as identity primary key,
    user_id uuid references auth.users(id) on delete set null,
    title text not null,
    type text,
    priority text not null default 'low' check (priority in ('low', 'mid', 'high')),
    description text not null,
    contact text,
    status text not null default 'pending' check (status in ('pending', 'approved', 'rejected')),
    admin_note text,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

drop trigger if exists trg_tickets_updated_at on public.tickets;
create trigger trg_tickets_updated_at
before update on public.tickets
for each row execute function public.set_updated_at();

-- ---------- 专栏密码锁 ----------
-- column_key = '__default__' 表示该用户的默认专栏密码；其余为具体专栏（作者 key）。
create table if not exists public.column_locks (
    id bigint generated by default as identity primary key,
    user_id uuid not null references auth.users(id) on delete cascade,
    column_key text not null,
    column_name text not null,
    password_hash text not null,
    is_default boolean not null default false,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

create unique index if not exists uq_column_locks_user_key
    on public.column_locks (user_id, column_key);
create unique index if not exists uq_column_locks_public_key
    on public.column_locks (column_key)
    where is_default = false;

drop trigger if exists trg_column_locks_updated_at on public.column_locks;
create trigger trg_column_locks_updated_at
before update on public.column_locks
for each row execute function public.set_updated_at();

-- ---------- 管理员判定 ----------
create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
    select exists (
        select 1
        from public.profiles
        where id = auth.uid()
          and role = 'admin'
          and status = 'active'
    );
$$;

-- ---------- 新用户自动建 profile ----------
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
    v_nickname text;
    v_contact text;
    v_qq text;
    v_luogu text;
    v_cf text;
    v_role text := 'user';
    v_status text := 'pending';
begin
    v_nickname := coalesce(nullif(new.raw_user_meta_data->>'nickname', ''), split_part(coalesce(new.email, 'user'), '@', 1));
    v_contact := nullif(new.raw_user_meta_data->>'contact', '');
    v_qq := nullif(new.raw_user_meta_data->>'qq', '');
    v_luogu := nullif(new.raw_user_meta_data->>'luogu', '');
    v_cf := nullif(new.raw_user_meta_data->>'cf', '');

    insert into public.profiles (id, nickname, contact, qq, luogu, cf, role, status)
    values (new.id, v_nickname, v_contact, v_qq, v_luogu, v_cf, v_role, v_status)
    on conflict (id) do nothing;
    return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
after insert on auth.users
for each row execute function public.handle_new_user();

-- ---------- 防止普通用户自行提权 ----------
create or replace function public.protect_profile_fields()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
    if auth.uid() is not null and not public.is_admin() then
        if new.role is distinct from old.role or new.status is distinct from old.status then
            raise exception '只有管理员可以修改 role / status';
        end if;
    end if;
    return new;
end;
$$;

drop trigger if exists trg_protect_profile_fields on public.profiles;
create trigger trg_protect_profile_fields
before update on public.profiles
for each row execute function public.protect_profile_fields();

-- ---------- RLS ----------
alter table public.profiles enable row level security;
alter table public.tickets enable row level security;
alter table public.column_locks enable row level security;

drop policy if exists profiles_select_self_or_admin on public.profiles;
create policy profiles_select_self_or_admin on public.profiles
for select to authenticated
using (auth.uid() = id or public.is_admin());

drop policy if exists profiles_update_self on public.profiles;
create policy profiles_update_self on public.profiles
for update to authenticated
using (auth.uid() = id)
with check (auth.uid() = id);

drop policy if exists profiles_update_admin on public.profiles;
create policy profiles_update_admin on public.profiles
for update to authenticated
using (public.is_admin())
with check (public.is_admin());

drop policy if exists tickets_insert_self on public.tickets;
create policy tickets_insert_self on public.tickets
for insert to authenticated
with check (auth.uid() = user_id);

drop policy if exists tickets_select_self_or_admin on public.tickets;
create policy tickets_select_self_or_admin on public.tickets
for select to authenticated
using (auth.uid() = user_id or public.is_admin());

drop policy if exists tickets_update_admin on public.tickets;
create policy tickets_update_admin on public.tickets
for update to authenticated
using (public.is_admin())
with check (public.is_admin());

drop policy if exists column_locks_select_self_or_admin on public.column_locks;
create policy column_locks_select_self_or_admin on public.column_locks
for select to authenticated
using (auth.uid() = user_id or public.is_admin());

-- ---------- 用户修改自己的专栏密码 ----------
create or replace function public.set_column_password(p_key text, p_password text)
returns void
language plpgsql
security definer
set search_path = public, extensions
as $$
declare
    v_user uuid := auth.uid();
begin
    if v_user is null then
        raise exception '未登录';
    end if;
    if length(coalesce(p_password, '')) < 6 then
        raise exception '密码至少 6 位';
    end if;

    if p_key = '__default__' then
        insert into public.column_locks (user_id, column_key, column_name, password_hash, is_default)
        values (v_user, '__default__', '默认专栏访问密码', crypt(p_password, gen_salt('bf')), true)
        on conflict (user_id, column_key)
        do update set password_hash = excluded.password_hash, updated_at = now();
    else
        update public.column_locks
        set password_hash = crypt(p_password, gen_salt('bf')), updated_at = now()
        where user_id = v_user
          and column_key = p_key
          and is_default = false;
        if not found then
            raise exception '专栏不存在或无权修改';
        end if;
    end if;
end;
$$;

revoke all on function public.set_column_password(text, text) from public;
grant execute on function public.set_column_password(text, text) to authenticated;

-- ---------- 校验专栏密码（读者可用，无需登录） ----------
create or replace function public.verify_column_password(p_key text, p_password text)
returns boolean
language sql
stable
security definer
set search_path = public, extensions
as $$
    select exists (
        select 1
        from public.column_locks
        where column_key = p_key
          and is_default = false
          and password_hash = crypt(p_password, password_hash)
    );
$$;

revoke all on function public.verify_column_password(text, text) from public;
grant execute on function public.verify_column_password(text, text) to anon, authenticated;

-- ---------- 初始化脚本专用（仅 service_role 可调用） ----------
create or replace function public.admin_set_column_password(
    p_user_id uuid,
    p_key text,
    p_password text,
    p_column_name text default null
)
returns void
language plpgsql
security definer
set search_path = public, extensions
as $$
begin
    if p_key = '__default__' then
        insert into public.column_locks (user_id, column_key, column_name, password_hash, is_default)
        values (p_user_id, '__default__', '默认专栏访问密码', crypt(p_password, gen_salt('bf')), true)
        on conflict (user_id, column_key)
        do update set password_hash = excluded.password_hash, updated_at = now();
    else
        insert into public.column_locks (user_id, column_key, column_name, password_hash, is_default)
        values (p_user_id, p_key, coalesce(p_column_name, p_key), crypt(p_password, gen_salt('bf')), false)
        on conflict (column_key) where is_default = false
        do update set
            user_id = excluded.user_id,
            column_name = excluded.column_name,
            password_hash = excluded.password_hash,
            updated_at = now();
    end if;
end;
$$;

revoke all on function public.admin_set_column_password(uuid, text, text, text) from public, anon, authenticated;
grant execute on function public.admin_set_column_password(uuid, text, text, text) to service_role;

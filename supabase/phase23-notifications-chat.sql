-- ============================================================
-- 第二十三阶段：通知栏（系统通知 + 私聊）
-- 前置：phase2（profiles / tickets）、phase3（columns）、phase15（profiles.avatar_url）
-- 在 Supabase SQL Editor 整段执行，可重复执行。
--
-- 变更：
--   1. notifications：站内系统通知（当前只有“修改工单通知专栏作者”）；
--   2. chat_messages：用户之间一对一私聊（仅文字）；
--   3. 触发器：有人提交「修改」工单时，自动通知目标专栏作者；
--   4. chat_directory()：给登录用户提供可聊天对象（昵称 / 头像），
--      因为 profiles 的 RLS 只允许读自己，不能直接查全站用户。
--
-- 安全说明：
--   - 两张表都开 RLS：通知只能读/标记自己的；私聊只能读自己参与的；
--   - 表只授予 read_at 的 update 权限，避免改正文/发信人；
--   - notifications 没有 insert 策略，只有 SECURITY DEFINER 触发器能写。
-- ============================================================

-- ---------- 1. 系统通知 ----------
create table if not exists public.notifications (
    id bigint generated by default as identity primary key,
    user_id uuid not null references public.profiles(id) on delete cascade,
    kind text not null default 'system',
    title text not null,
    body text,
    link text,
    ticket_id bigint,
    read_at timestamptz,
    created_at timestamptz not null default now()
);

create index if not exists idx_notifications_user_created
    on public.notifications (user_id, created_at desc);

alter table public.notifications enable row level security;

drop policy if exists notifications_select_self on public.notifications;
create policy notifications_select_self on public.notifications
for select to authenticated
using (auth.uid() = user_id);

drop policy if exists notifications_update_self on public.notifications;
create policy notifications_update_self on public.notifications
for update to authenticated
using (auth.uid() = user_id)
with check (auth.uid() = user_id);

-- 只允许改 read_at，不能改内容
revoke all on public.notifications from anon, authenticated;
grant select on public.notifications to authenticated;
grant update (read_at) on public.notifications to authenticated;

-- ---------- 2. 修改工单 → 通知专栏作者 ----------
create or replace function public.notify_edit_ticket_owner()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
    v_owner uuid;
    v_column_name text;
    v_submitter text;
    v_note text;
begin
    if new.type is distinct from 'edit' then
        return new;
    end if;

    select c.owner_id, c.column_name
    into v_owner, v_column_name
    from public.columns c
    where c.column_key = coalesce(new.payload->>'column_key', '');

    -- 专栏没有作者、或提交者本人就是作者时，不通知
    if v_owner is null or v_owner = new.user_id then
        return new;
    end if;

    select coalesce(nullif(p.nickname, ''), '有用户')
    into v_submitter
    from public.profiles p
    where p.id = new.user_id;

    v_note := nullif(btrim(coalesce(new.payload->>'note', '')), '');

    insert into public.notifications (user_id, kind, title, body, link, ticket_id)
    values (
        v_owner,
        'edit_ticket',
        '你的专栏收到修改工单',
        coalesce(v_column_name, new.title) ||
            coalesce(' · 说明：' || v_note, ' · 未填写修改说明') ||
            ' · 提交者：' || coalesce(v_submitter, '匿名用户'),
        'admin.html?tab=profile',
        new.id
    );

    return new;
end;
$$;

drop trigger if exists trg_notify_edit_ticket_owner on public.tickets;
create trigger trg_notify_edit_ticket_owner
after insert on public.tickets
for each row execute function public.notify_edit_ticket_owner();

-- ---------- 3. 私聊消息 ----------
create table if not exists public.chat_messages (
    id bigint generated by default as identity primary key,
    sender_id uuid not null references public.profiles(id) on delete cascade,
    recipient_id uuid not null references public.profiles(id) on delete cascade,
    body text not null check (char_length(btrim(body)) between 1 and 2000),
    read_at timestamptz,
    created_at timestamptz not null default now()
);

create index if not exists idx_chat_pair_created
    on public.chat_messages (sender_id, recipient_id, created_at);
create index if not exists idx_chat_unread
    on public.chat_messages (recipient_id, read_at);

alter table public.chat_messages enable row level security;

drop policy if exists chat_select_participants on public.chat_messages;
create policy chat_select_participants on public.chat_messages
for select to authenticated
using (auth.uid() = sender_id or auth.uid() = recipient_id);

drop policy if exists chat_insert_sender on public.chat_messages;
create policy chat_insert_sender on public.chat_messages
for insert to authenticated
with check (sender_id = auth.uid() and recipient_id <> auth.uid());

drop policy if exists chat_update_recipient on public.chat_messages;
create policy chat_update_recipient on public.chat_messages
for update to authenticated
using (recipient_id = auth.uid())
with check (recipient_id = auth.uid());

revoke all on public.chat_messages from anon, authenticated;
grant select, insert on public.chat_messages to authenticated;
grant update (read_at) on public.chat_messages to authenticated;

-- ---------- 4. 可聊天对象 ----------
create or replace function public.chat_directory(p_query text default null)
returns table (id uuid, nickname text, avatar_url text)
language sql
stable
security definer
set search_path = public
as $$
    select
        p.id,
        coalesce(nullif(btrim(p.nickname), ''), '未命名用户') as nickname,
        p.avatar_url
    from public.profiles p
    where p.status = 'active'
      and p.id <> coalesce(auth.uid(), '00000000-0000-0000-0000-000000000000'::uuid)
      and (
          coalesce(btrim(p_query), '') = ''
          or p.nickname ilike '%' || btrim(p_query) || '%'
      )
    order by p.nickname
    limit 200;
$$;

revoke all on function public.chat_directory(text) from public, anon;
grant execute on function public.chat_directory(text) to authenticated;

notify pgrst, 'reload schema';

-- ---------- 自检 ----------
select table_name, column_name, data_type
from information_schema.columns
where table_schema = 'public'
  and table_name in ('notifications', 'chat_messages')
order by table_name, ordinal_position;

select proname, pg_get_function_identity_arguments(oid) as args
from pg_proc
where pronamespace = 'public'::regnamespace
  and proname in ('notify_edit_ticket_owner', 'chat_directory')
order by proname;

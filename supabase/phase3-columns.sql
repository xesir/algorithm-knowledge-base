-- ---------- 专栏表 ----------
-- 一个作者/用户可以有多个专栏；column_key 与 column_locks.column_key 对应。
create table if not exists public.columns (
    id bigint generated by default as identity primary key,
    owner_id uuid not null references auth.users(id) on delete cascade,
    column_key text not null unique,
    column_name text not null,
    description text,
    content text,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

drop trigger if exists trg_columns_updated_at on public.columns;
create trigger trg_columns_updated_at
before update on public.columns
for each row execute function public.set_updated_at();

alter table public.columns enable row level security;

drop policy if exists columns_select_public on public.columns;
create policy columns_select_public on public.columns
for select using (true);

drop policy if exists columns_update_owner on public.columns;
create policy columns_update_owner on public.columns
for update to authenticated
using (auth.uid() = owner_id)
with check (auth.uid() = owner_id);

drop policy if exists columns_update_admin on public.columns;
create policy columns_update_admin on public.columns
for update to authenticated
using (public.is_admin())
with check (public.is_admin());

drop policy if exists columns_insert_admin on public.columns;
create policy columns_insert_admin on public.columns
for insert to authenticated
with check (public.is_admin());

drop policy if exists columns_delete_admin on public.columns;
create policy columns_delete_admin on public.columns
for delete to authenticated
using (public.is_admin());

-- ---------- 密码允许为空（空 = 无密码 / 跟随通用密码） ----------
alter table public.column_locks alter column password_hash drop not null;

-- ---------- 设置密码（空字符串表示清除） ----------
create or replace function public.set_column_password(p_key text, p_password text)
returns void
language plpgsql
security definer
set search_path = public, extensions
as $$
declare
    v_user uuid := auth.uid();
    v_plain text := nullif(btrim(coalesce(p_password, '')), '');
    v_hash text;
begin
    if v_user is null then
        raise exception '未登录';
    end if;

    if v_plain is not null then
        if length(v_plain) < 6 then
            raise exception '密码至少 6 位；留空表示无密码';
        end if;
        v_hash := crypt(v_plain, gen_salt('bf'));
    end if;

    if p_key = '__default__' then
        insert into public.column_locks (user_id, column_key, column_name, password_hash, is_default)
        values (v_user, '__default__', '默认专栏访问密码', v_hash, true)
        on conflict (user_id, column_key)
        do update set password_hash = excluded.password_hash, updated_at = now();
    else
        insert into public.column_locks (user_id, column_key, column_name, password_hash, is_default)
        select v_user, c.column_key, c.column_name, v_hash, false
        from public.columns c
        where c.owner_id = v_user
          and c.column_key = p_key
        on conflict (column_key) where is_default = false
        do update set
            user_id = excluded.user_id,
            column_name = excluded.column_name,
            password_hash = excluded.password_hash,
            updated_at = now();

        if not found then
            raise exception '专栏不存在或无权修改';
        end if;
    end if;
end;
$$;

revoke all on function public.set_column_password(text, text) from public;
grant execute on function public.set_column_password(text, text) to authenticated;

-- ---------- 校验密码：特定 > 通用 > 无密码 ----------
create or replace function public.verify_column_password(p_key text, p_password text)
returns boolean
language sql
stable
security definer
set search_path = public, extensions
as $$
    select exists (
        select 1
        from public.columns c
        left join public.column_locks s
            on s.column_key = c.column_key and s.is_default = false
        left join public.column_locks d
            on d.user_id = c.owner_id and d.is_default = true
        where c.column_key = p_key
          and (
              (s.password_hash is not null and s.password_hash = crypt(p_password, s.password_hash))
              or (s.password_hash is null and d.password_hash is null)
              or (s.password_hash is null and d.password_hash = crypt(p_password, d.password_hash))
          )
    );
$$;

revoke all on function public.verify_column_password(text, text) from public;
grant execute on function public.verify_column_password(text, text) to anon, authenticated;

-- ---------- 当前用户密码设置状态（不返回 hash） ----------
create or replace function public.get_column_lock_status(p_key text)
returns table(default_set boolean, specific_set boolean)
language sql
stable
security definer
set search_path = public
as $$
    select
        exists (
            select 1 from public.column_locks
            where user_id = auth.uid()
              and is_default = true
              and password_hash is not null
        ),
        exists (
            select 1 from public.column_locks
            where user_id = auth.uid()
              and is_default = false
              and column_key = p_key
              and password_hash is not null
        );
$$;

revoke all on function public.get_column_lock_status(text) from public;
grant execute on function public.get_column_lock_status(text) to authenticated;

-- ---------- 初始化脚本专用（service_role） ----------
create or replace function public.admin_set_column_password(
    p_user_id uuid,
    p_key text,
    p_password text,
    p_column_name text default null
)
returns void
language plpgsql
security definer
set search_path = public, extensions
as $$
declare
    v_plain text := nullif(btrim(coalesce(p_password, '')), '');
    v_hash text;
begin
    if v_plain is not null then
        v_hash := crypt(v_plain, gen_salt('bf'));
    end if;

    if p_key = '__default__' then
        insert into public.column_locks (user_id, column_key, column_name, password_hash, is_default)
        values (p_user_id, '__default__', '默认专栏访问密码', v_hash, true)
        on conflict (user_id, column_key)
        do update set password_hash = excluded.password_hash, updated_at = now();
    else
        insert into public.column_locks (user_id, column_key, column_name, password_hash, is_default)
        values (p_user_id, p_key, coalesce(p_column_name, p_key), v_hash, false)
        on conflict (column_key) where is_default = false
        do update set
            user_id = excluded.user_id,
            column_name = excluded.column_name,
            password_hash = excluded.password_hash,
            updated_at = now();
    end if;
end;
$$;

revoke all on function public.admin_set_column_password(uuid, text, text, text) from public, anon, authenticated;
grant execute on function public.admin_set_column_password(uuid, text, text, text) to service_role;


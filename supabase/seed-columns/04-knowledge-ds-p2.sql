## 核心公式 / 状态定义与转移方程

数据结构没有统一的状态转移，但有一套统一的设计语言：

1. **列出操作**：需要支持查询什么、修改什么、是否强制在线。
2. **估算代价**：每个操作允许的复杂度由总操作数决定。
3. **选择结构**：根据“单点/区间”“可减/不可减”“静态/动态”“是否有版本”选型。
4. **维护不变量**：例如树状数组的 `lowbit` 分段、线段树的区间覆盖、平衡树的 BST 性质、并查集的代表元。

不变量一旦被破坏，查询结果就会错；所有旋转、合并、路径压缩都只是在不变量允许的范围内调整形态。


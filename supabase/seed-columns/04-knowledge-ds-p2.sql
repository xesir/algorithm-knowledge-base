分块的核心思想是**把序列（或值域、操作序列、树）切成大小约为 $\sqrt n$ 的块**，块内暴力、块间整体处理。它的复杂度通常比线段树多一个 $\sqrt n$，但实现简单、常数小，而且能处理线段树很难维护的信息（区间众数、区间不同数个数、区间 $\le k$ 的个数等）。

本页是「数据结构」大类下的二级总述，按「对什么分块」把相关知识点分成七组：

- **序列分块**：区间加 / 区间求和、区间 $\le k$ 的个数、区间开根等（`ds-block-decomposition`）。
- **莫队**：把询问按块排序，用指针在相邻询问之间移动（普通莫队、带修莫队、回滚莫队，`ds-mo-team`、`ds-mo-team-modify`）。
- **值域分块**：对值域而非下标分块，用于第 $k$ 小、mex、值出现次数统计（`ds-block-value-domain`）。
- **时间分块（操作分块）**：把修改/询问按时间切块，块内暴力重做、块间复用（`ds-block-time`）。
- **树分块**：在树上按深度或关键点分块，处理树上路径统计（`ds-block-tree`）。
- **二维分块**：矩阵与二维数点类问题（`ds-block-2d`）。
- **块状链表与 Sqrt Tree**：把块做成链表以支持插入删除（`ds-fast-block-list`、`ds-index-tree-block-list`），以及在块上建静态 RMQ 结构（`ds-sqrt-tree`）。

## 核心公式 / 状态定义与转移方程

- 块长通常取 $B=\lfloor\sqrt n\rfloor$ 或 $\sqrt{n\log n}$；块数 $n/B$。
- 单次修改/查询：整块 $O(n/B)$ 个 + 零散 $O(B)$ 个元素，取 $B=\sqrt n$ 得 $O(\sqrt n)$。
- 莫队：块长取 $n/\sqrt m$ 时总复杂度约 $O(n\sqrt m)$；带修莫队块长取 $n^{2/3}$，复杂度约 $O(n^{5/3})$。
- 值域分块：值域 $V$ 上的查询为 $O(\sqrt V)$。
- Sqrt Tree：$O(n\log\log n)$ 预处理，$O(1)$ 区间查询。


## 复杂度分析

- **时间复杂度**：$O(\alpha(n))$ 每次。路径压缩使均摊查询/合并接近常数。`k[]` 的累加发生在 `find` 中，不增加额外的时间复杂度。
- **空间复杂度**：$O(n)$，需要三个数组 `A`（父节点）、`k`（距离）、`sz`（链大小），各 $O(n)$。使用 `long long` 以防止距离累加溢出。

## 适用场景

- 需要查询元素间排名/距离的链式合并问题（如排队、链合并后查询间隔人数）。
- 元素间存在线性顺序关系，需要在动态合并中维护相对位置。
- 蓝桥 1156 类问题：合并两条链后查询两元素间相隔多少个元素。
- 可推广至任何需要维护"节点到根的权值/距离"的场景，是带权并查集的基础形态。

## 常见陷阱与注意事项

- **find 中必须先保存旧父 `old` 再递归**：这是最常见的错误。若先递归再取 `old = A[idx]`，此时 `A[idx]` 已被更新为根，`old` 就不再是旧父，`k[old]` 也无意义。正确顺序是 `old = A[idx]` 在递归之前。
- **k 和 A 的更新顺序在 find 中至关重要**：先递归 `find(A[idx])`（更新父节点和 k[old]），再判断 `old != A[idx]` 并累加 `k[idx] += k[old]`。顺序颠倒会导致累加错误的值。
- **unity 中 k[rx] 和 sz[ry] 的更新顺序**：必须先 `k[rx] = sz[ry]`（用旧 sz），再 `sz[ry] += sz[rx]`（更新 sz）。若先更新 sz 再设 k，会导致 `k[rx]` 取到合并后的大小。
- **数据类型**：距离累加可能超过 `int` 范围（特别是 N 较大时），使用 `long long` 更安全。
- **查询时必须先 find 再读 k**：`k[x]` 只有在 `find(x)` 之后才是最新的。直接读取未经 `find` 的 `k[x]` 可能是过时的值。
- **查询 x==y 会得到 -1 而非 0**：`|k[x]-k[y]|-1` 在 x==y 时为 -1，而同一元素之间应无中间节点（结果应为 0）。若题目保证查询的两元素不同可忽略；否则应加 `if(x == y)` 直接输出 0 的判断。


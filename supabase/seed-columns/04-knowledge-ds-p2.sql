## 核心操作详解

### init() —— 初始化

**功能**：为 `N` 个元素各自创建独立的单节点链。

**参数**：无（使用全局变量 `N`）。

**算法步骤**：
1. `A` 数组大小为 `N + 1`，每个元素 `A[i] = i`（自身为根）。
2. `k` 数组大小为 `N + 1`，全部初始化为 0（到自身距离为 0）。
3. `sz` 数组大小为 `N + 1`，全部初始化为 1（单节点链大小为 1）。

**关键细节**：三个数组缺一不可。`k[]` 记录到根距离，`sz[]` 记录链大小（用于合并时计算新根的距离）。

### find(idx) —— 查找（带路径压缩 + 距离累加）

**功能**：返回元素 `idx` 所在链的根节点，同时压缩路径并更新距离 `k[]`。

**参数**：`idx` — 待查找的元素编号。

**算法步骤**：
1. 保存旧父节点 `old = A[idx]`。
2. 若 `A[idx] != idx`（不是根），递归调用 `find(A[idx])` 找到根并压缩路径，将 `A[idx]` 更新为根。
3. 判断 `old != A[idx]`（即父节点发生了变化，说明路径被压缩）。
4. 若父节点变化，执行 `k[idx] += k[old]`——将旧父到新根的距离累加到当前节点的距离上。
5. 返回 `A[idx]`（根节点）。

**关键细节**：**必须先保存旧父 `old` 再递归**。递归 `find(A[idx])` 会改变 `A[idx]` 的值，若不提前保存，将无法获取旧父节点的 `k` 值。这一顺序是正确性的核心——`k[old]` 在递归后已被更新为 `old` 到新根的距离，此时累加才是正确的。

### unity(x, y) —— 合并（将 x 链追加到 y 链末尾）

**功能**：将 `x` 所在链追加到 `y` 所在链的末尾，合并为一条链。

**参数**：`x`、`y` — 两个元素编号。合并后 `y` 链的根成为新链的根。

**算法步骤**：
1. 调用 `find(x)` 和 `find(y)` 获取两链的根 `rx` 和 `ry`。
2. 若 `rx == ry`（已在同一链），返回 `false`（无需合并）。
3. 设置 `k[rx] = sz[ry]`——x 链根 `rx` 到新根 `ry` 的距离等于 y 链当前大小。
4. 更新 `sz[ry] += sz[rx]`——新链大小 = 两链大小之和。
5. 执行 `A[rx] = ry`——将 x 链根挂到 y 链根下。
6. 返回 `true`。

**关键细节**：**顺序不能颠倒**——必须先设置 `k[rx]` 再更新 `sz[ry]`，否则 `k[rx]` 会用到更新后的 `sz[ry]` 导致错误。`k[rx] = sz[ry]` 的含义是：x 链排在整个 y 链后面，所以 x 链根距离 y 链根的距离恰好是 y 链的长度。


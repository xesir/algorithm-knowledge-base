带权并查集在普通并查集的基础上，额外维护每个节点到根节点的**距离（权值）**。本题（蓝桥 1156）的场景是将元素排成链式队列：合并操作 `unity(x, y)` 表示将 `x` 所在的整条链追加到 `y` 所在链的末尾，查询操作需要计算两个元素之间相隔多少个节点。

核心维护的数组有三个：`A[]`（父节点）、`k[]`（到根的距离/链长）、`sz[]`（以该节点为根的链的大小）。初始时 $A[i] = i$（各自成链），$k[i] = 0$（到自己距离为 0），$sz[i] = 1$（单节点链大小为 1）。

**合并的关键洞察**：当执行 `unity(x, y)` 将 x 链追加到 y 链末尾时，x 链的根 `rx` 被挂到 y 链的根 `ry` 下。此时 `rx` 到新根 `ry` 的距离应当等于 y 链当前的长度 $\text{sz}[r_y]$——因为 x 链整体排在了 y 链之后，x 链的根距离 y 链根的距离正好是 y 链中所有节点的个数。因此执行 $k[r_x] = \text{sz}[r_y]$，然后更新 $\text{sz}[r_y] \mathrel{+}= \text{sz}[r_x]$（新链大小 = 两条链大小之和），最后 $A[r_x] = r_y$。

**路径压缩时距离的累加**是本实现最精妙的部分。在 `find` 中，当节点 `idx` 的父节点从 `old` 变为新的根时（即 `old != A[idx]`，说明路径被压缩了），`k[idx]` 需要加上 `k[old]`。原因是：`k[idx]` 原本记录的是 `idx` 到旧父 `old` 的距离，而 `k[old]` 在递归 `find` 后已经更新为 `old` 到新根的距离。两者相加 $k[\text{idx}] + k[\text{old}]$ 即为 `idx` 到新根的总距离。这一累加发生在路径压缩的同时，保证了距离信息始终正确。

**查询逻辑**：若两节点 `x` 和 `y` 在同一链中（`find(x) == find(y)`），则它们之间的间隔节点数为 $|k[x] - k[y]| - 1$。$|k[x] - k[y]|$ 是两节点在链中的位置差（距离），减去 1 是因为要排除端点本身，只计算中间的节点数。若不在同一链中则输出 -1。


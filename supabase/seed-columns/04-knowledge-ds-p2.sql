本大类覆盖的内容可以按维护对象分成几组：

- **静态区间信息**：前缀和与差分、ST 表。
- **动态区间信息**：树状数组、线段树、分块、莫队。
- **有序集合与版本**：平衡树、字典树、可持久化数据结构。
- **连通性与特殊结构**：并查集、堆、栈、单调队列、笛卡尔树。

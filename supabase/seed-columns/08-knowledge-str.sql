字符串哈希的核心思想是将字符串映射为一个整数，通过比较整数来替代逐字符比较。多项式滚动哈希把长度为 $n$ 的字符串 $s$ 视为一个 $p$ 进制数，每一位字符的 ASCII 值充当该进制的"数字"，整个字符串的多项式求值结果即为哈希值。由于不同字符串对应不同多项式值的概率极高（在合理选取基数和模数的前提下），这种映射可以在极低冲突率下实现 $O(1)$ 的子串等价判定。

为了支持任意子串的快速哈希查询，算法引入前缀哈希数组 `sum` 和基数幂次数组 `P`。前缀哈希 `sum[i]` 记录前 $i$ 个字符的多项式值，幂次数组 `P[i]` 预存 $q^i$。查询子串 $s[l..r]$ 的哈希时，只需将 `sum[l-1]` 左移（乘以）$q^{r-l+1}$ 对齐到与 `sum[r]` 相同的位权，再做减法即可。这一"高位对齐"技巧是前缀哈希能在 $O(1)$ 内求出子串哈希的关键。

本代码采用 `unsigned long long`（64 位无符号整数）存储哈希值，利用其自然溢出实现对 $2^{64}$ 取模的效果。这种做法省去了显式的取模运算（`%`），在常数上比显式取模更快，是竞赛中常见的写法。代价是模数固定为 $2^{64}$，存在被构造数据针对（如 Thue-Morse 串反哈希）的风险，在对抗性较强的场景中需考虑双哈希。

## 核心公式

前缀哈希递推：
$$\text{sum}[i+1] = \text{sum}[i] \times q + s[i] \pmod{2^{64}}$$

展开后的前缀哈希通项：
$$\text{sum}[i] = \sum_{j=1}^{i} s[j] \times q^{i-j} \pmod{2^{64}}$$

幂次数组递推：
$$P[i] = P[i-1] \times q, \quad P[0] = 1$$

子串 $s[l..r]$ 的哈希值（高位对齐后相减）：
$$H(l, r) = \text{sum}[r] - \text{sum}[l-1] \times P[r-l+1] \pmod{2^{64}}$$


## 复杂度分析

虽然外层 `while` 循环和内层 `k` 的比较看起来像嵌套循环，但关键在于指针 $i$ 和 $j$ 每次跳跃至少前进 $k+1$ 位，且 $k$ 是本轮新匹配的字符数。在整个算法执行过程中，$i$、$j$ 均不超过 $n$，而 $k$ 的累计增加值（即总比较次数）受 $i + j$ 的总移动量约束，最多为 $2n$。因此总比较次数为 $O(n)$，算法整体时间复杂度为 $O(n)$。拼接字符串额外使用 $O(n)$ 空间。


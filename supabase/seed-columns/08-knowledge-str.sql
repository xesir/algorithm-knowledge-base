### 预处理偏移表 init

```cpp
void init(const string& str)
{
    int m = str.size();
    sunday_next.assign(128, m + 1);  // 初始所有字符的移动步数为 m+1
    for (int i = 0; i < m; i++)
        sunday_next[str[i]] = m - i; // 字符 str[i] 出现在位置 i，移动 m-i 步
}
```

**关键点**：
- 数组大小 128，对应 ASCII 码表的所有字符
- 初始值设为 $m+1$（不在模式串中的字符移动 $m+1$ 位）
- 从左到右遍历，后面的位置会覆盖前面的，因此最终每个字符保存的是**最右边**的出现位置

### Sunday 匹配主体

```cpp
void sunday(const string& a, const string& b)
{
    ans.clear();
    int n = a.size(), m = b.size();
    for (int i = 0; i <= n - m; i += sunday_next[a[i + m]])
    {
        int j = 0;
        while (j < m && a[i + j] == b[j]) j++;  // 逐字符比较
        if (j == m) ans.emplace_back(i);        // 完全匹配，记录位置
    }
}
```

**逐行解读**：

| 代码 | 含义 |
|------|------|
| `for (int i = 0; i <= n - m; ...)` | $i$ 是主串当前窗口的起始位置，最多到 $n-m$ |
| `i += sunday_next[a[i + m]]` | 匹配失败后，根据窗口右边第一个字符 $s[i+m]$ 查偏移表，移动相应步数 |
| `while (j < m && a[i + j] == b[j]) j++` | 从左到右逐字符比较，j 是匹配成功的字符数 |
| `if (j == m)` | 所有字符都匹配上了，说明找到一个匹配位置 |
| `ans.emplace_back(i)` | 记录匹配的起始下标 |


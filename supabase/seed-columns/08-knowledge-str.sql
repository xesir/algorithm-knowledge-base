    if (t[j + 1] == t[i]) j++;                  // 能接上就延长一位
    nxt[i] = j;                                 // 记录 t[1..i] 的最长 border
}
```

- `i` 从 2 开始：`nxt[1]` 恒为 0，不需要算，`j` 初值为 0 正好对应它。
- `while` 里的 `j &&` 是**边界哨兵**：保证不会访问 `t[0]`，也保证 `nxt[j]` 的下标合法。
- 比较的是 `t[j + 1]` 和 `t[i]`（1-indexed 的前缀-后缀对位），不是 `t[j]` 与 `t[i]`。
- 循环结束时 `j` 就是 $t[1 \dots i]$ 的最长 border 长度，直接写进 `nxt[i]`。


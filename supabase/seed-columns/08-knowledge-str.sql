5. **数组大小**：`c` 数组大小应为「节点数 × 26」，节点数约为 $\sum \lvert s_i\rvert$，不要开小。
6. **`#define int long long` 的代价**：所有 `int` 变成 64 位，`c[N][26]` 等数组内存翻倍，$N$ 较大时可能 MLE；`main` 需写成 `signed main`。


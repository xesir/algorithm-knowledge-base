## 常见陷阱与注意事项

1. **哈希冲突**：单哈希（尤其是模 $2^{64}$）可被构造数据针对。安全场景下建议使用双哈希（两组不同基数和质数模数，如 $10^9+7$ 与 $10^9+9$），将冲突概率降至 $O(1/M_1 M_2)$。
2. **基数选择**：基数应大于字符集大小且最好为质数。若基数小于 128，则 ASCII 值可能超过基数导致"进位歧义"（如 `'a'` = 97，若 $q=10$ 则多位混淆）。
3. **自然溢出的安全风险**：模 $2^{64}$ 不是质数，存在结构性弱点。Thue-Morse 串等特殊构造可使 $2^{64}$ 模哈希产生大量冲突，比赛中遇到hack时需改用质数模数。
4. **下标越界**：`sum[l-1]` 当 $l=1$ 时访问 `sum[0]`，必须保证数组从 0 开始且初始化为 0，否则读取到未定义值。
5. **子串长度为 0**：当 $l > r$ 时公式仍会返回值但无意义，调用前应确保 $l \le r$。
6. **大写/小写与编码**：直接用 `str[i]` 作为"数字"时，大小写字母 ASCII 值不同但可能产生非预期行为，需根据题目统一编码。


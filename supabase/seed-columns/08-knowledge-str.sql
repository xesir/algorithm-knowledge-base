## 常见陷阱与注意事项

1. **内层比较的短路顺序**：`str += str` 后字符串长度为 $2n$，`i + k` 和 `j + k` 最大可达 $2n - 1$。内层条件必须写成 `k < n && str[i + k] == str[j + k]`（`k < n` 在前）：当 $k$ 达到 $n$ 时短路停止，不再访问 `str[i+k]`，既避免误读拼接后的第二份拷贝，也规避了顺序颠倒时可能的下标越界。
2. **`i == j` 未处理**：跳跃后两指针可能重合，若不错开则进入无限自比循环。代码中 `if(j == i) j++` 和 `if(i == j) i++` 必不可少。
3. **`k == n` 的含义**：当 $k$ 达到 $n$ 时并非找到了最小表示，而是说明两个不同起点的串完全相同，即整串存在周期 $|i-j|$（如 "abab" 这类周期串，而不仅是 "aaaa"）。此时直接 `break` 跳出循环，返回 `min(i,j)`，无需再作特殊标记。
4. **空串处理**：函数开头 `if (n == 0) return 0` 显式处理空串，直接返回起点 $0$，避免空串进入双指针循环引发越界；`main` 中 $n = 0$ 时输出循环自然不执行。
5. **指针越界上限**：外层条件为 `i < n && j < n`，当其中一个指针达到或超过 $n$ 时停止，此时另一个即为答案。注意是 `< n` 而非 `< 2n`，因为只需在原串范围内寻找起点。


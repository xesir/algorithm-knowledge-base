1. **半径语义混用**：本模板 $p[i]$ 不含中心，右端点是 `i + p[i]`，答案就是 `max(p[i])`；网上大量模板的 $p[i]$ 含中心，右端点是 `i + p[i] - 1`，答案是 `max(p[i]) - 1`。两套只差常数 1，混着抄就会在边界上错得莫名其妙。
2. **扩展下标写错**：不含中心的写法比较的是 `t[i - p[i] - 1]` 和 `t[i + p[i] + 1]`；写成 `t[i - p[i]]` 与 `t[i + p[i]]` 就是含中心的写法，和继承来的 `p[i]` 语义对不上，会直接把中心字符算进半径。

> 给定一个字符串 $s$，求它的最长连续回文子串。

### 朴素做法

回文串有两种：奇数长度（如 `aba`，中心是一个字符）和偶数长度（如 `abba`，中心是两个字符之间的空隙）。

我们可以考虑给每个字符插隔板：`a|b|b|a`。这样每种对称中心都会有一个字符对应，即全都是奇数回文，方便处理。代码里用的是 `#`：`abba` 变成 `#a#b#b#a#`，长度 $2n+1$，奇偶两种回文被强行统一成了同一种。

最朴素的做法是：枚举每个可能的中心，向两边扩展，直到不能扩展为止。复杂度 $O(n^2)$，无法接受。

注意到在朴素做法中，**每个中心都从头开始扩展，大量回文信息被重复计算**。比如字符串 `aaaaa`，枚举每个中心都要扩展一遍，总扩展次数是 $O(n^2)$。

于是 Manacher 的优化核心就是：**利用已经找到的回文串的对称性，避免重复扩展**。

### 回文半径数组

定义 $p[i]$ 为：**以位置 $i$ 为中心的最长回文串的半径**（不含中心本身）。

对于展开后的串 `#a#b#b#a#`：

| $i$ | 0 | 1 | 2 | 3 | 4 | 5 | 6 | 7 | 8 |
| :---: | :---: | :---: | :---: | :---: | :---: | :---: | :---: | :---: | :---: |
| 字符 | `#` | `a` | `#` | `b` | `#` | `b` | `#` | `a` | `#` |
| $p[i]$ | 0 | 1 | 0 | 1 | 4 | 1 | 0 | 1 | 0 |

以 $i=4$ 为中心，回文串是 `#a#b#b#a#`，半径为 4。

**关键转化**：在原串中，以 $i$ 为中心的最长回文子串长度 = $p[i]$。所以**原串中最长回文子串的长度恰好等于 $\max(p[i])$**。这个「不含中心」的定义是本模板的约定，网上很多模板的半径是「含中心」的，两者差 1，右边界也要跟着差 1，别混着抄。

### 镜像对称

Manacher 的精髓在于：**利用已知回文串的对称性，直接继承一部分回文半径**。

维护两个变量：

- $C$：当前已知回文串中，**右端点最靠右**的那个回文串的中心；
- $R$：该回文串的右端点，即 $R = C + p[C]$。

当我们处理位置 $i$ 时，如果 $i < R$，说明 $i$ 在当前最右回文串的覆盖范围内。此时，$i$ 关于 $C$ 的**对称点**是 $i' = 2C - i$。

由于回文串的对称性，$p[i]$ 至少可以继承 $p[i']$ 的一部分：

$$p[i] \ge \min(p[i'],\ R - i)$$

由于 $p[i']$ 可能超出当前回文串的范围，超出部分无法保证对称性，所以取 $\min$。

**为什么能继承？** 以 $C$ 为中心、覆盖到 $R$ 的那个回文串，本身是一段左右镜像的文字。$i$ 和 $i'$ 关于 $C$ 对称，那么以 $i'$ 为中心、半径不超过 $R - i$ 的那一段回文，翻折过去就是以 $i$ 为中心、同样半径的一段回文——这段信息我们早就验证过了，不用再比。至于超出 $R$ 的部分，翻折过去落在 $R$ 左边界的更外侧，那里从来没被验证过，没有对称性可用，只能老实扩展。

还有一种情况值得单独说：如果 $p[i']$ 本身就短于 $R - i$，说明镜像点的回文根本没碰到边界，那么 $p[i]$ 就等于 $p[i']$——它俩被同一段大回文完全包住，一边扩不动，另一边也一定扩不动。

于是，Manacher 的流程是：

1. 如果 $i < R$，令 $p[i] = \min(p[2C-i], R-i)$；
2. 否则，$p[i] = 0$；
3. **暴力扩展**：从 $p[i]+1$ 开始，向两边扩展，直到不能扩展为止；
4. 更新 $C$ 和 $R$：如果 $i + p[i] > R$，令 $C = i$，$R = i + p[i]$。

## 核心公式 / 状态定义与转移方程

**状态定义**：

- $p[i]$：以展开串 $t[i]$ 为中心的回文半径，**不含中心本身**；
- $C$：当前最右回文串的中心；
- $R$：该回文串的右端点，$R = C + p[C]$（因为不含中心，右端点正好是中心加半径）；
- $ans$：过程中 $p$ 的最大值，也就是答案。

**镜像继承**：

$$p[i] = \begin{cases} \min(p[2C - i],\ R - i), & i < R \\ 0, & i \ge R \end{cases}$$

**中心扩展**（$t$ 的下标范围是 $[0, m)$）：

$$\text{while } i - p[i] - 1 \ge 0 \ \wedge\ i + p[i] + 1 < m \ \wedge\ t[i - p[i] - 1] = t[i + p[i] + 1]:\ p[i] \leftarrow p[i] + 1$$

**最右回文更新**：

$$\text{若 } i + p[i] > R:\ C \leftarrow i,\ R \leftarrow i + p[i]$$

**答案**：

$$ans = \max_i p[i]$$


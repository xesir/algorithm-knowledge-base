## 适用场景

- **一般文本 / 字符串匹配**：平均时间 $O(n/m)$，实践中通常比 KMP 更快，代码也更短
- **字符集较小的场合**：偏移表大小为 $O(|\Sigma|)$，ASCII 下开 128 即可
- **不适用**：题目刻意构造最坏数据（大量重复字符）时，Sunday 会退化到 $O(nm)$，此时应改用 KMP 保证 $O(n+m)$

## 常见陷阱与注意事项

1. **数组越界问题**：当 `i + m >= n` 时，`a[i+m]` 会越界。代码中 `i <= n - m` 的循环条件保证了最后一次可能匹配的窗口是合法的，但若最后一次匹配失败后需要继续移动，则会越界。因此匹配失败后如果无法再移动（`i + m >= n`），应直接退出
2. **偏移表初始化**：必须先全部设为 `m+1`，再用模式串中的字符覆盖。不能只初始化出现过的字符
3. **最右位置**：从左到右遍历时，后面的赋值会覆盖前面的，这样自然得到了每个字符的最右出现位置，无需额外处理
4. **字符集大小**：代码中用 128 对应 ASCII，如果是更大的字符集（如 Unicode）需要调整
5. **下标从 0 开始**：Sunday 算法通常用 0 下标实现，与 KMP 类似
6. **找所有匹配位置**：找到一个匹配后，移动步数仍按 `next[s[i+m]]` 计算（而不是移动 1 位），这样可以保持高效


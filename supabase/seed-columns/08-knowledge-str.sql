## 常见陷阱与注意事项

1. **单哈希会被卡**：模数和基数都固定时，存在针对性的构造串（如 Thue–Morse 串）能让单哈希大量冲突，出题人可以卡。稳妥做法是双哈希，或随机化基数。
2. **字符编码不要取 0**：如果让 `a` 映射为 0，那么 `"a"` 与 `"aa"` 的哈希都会是 0，直接冲突。建议 `a` 映射为 1。
3. **基数和模数的选择**：基数要大于字符集大小，且最好与模数互质；模数取大质数。自然溢出时模数被固定为 $2^{64}$。
4. **无符号与有符号不要混用**：自然溢出的正确性依赖无符号类型的模 $2^{64}$ 语义，中间量一旦被当成有符号数就可能出负数。
5. **下标与指数**：子串查询里是 `sum[l - 1]`、`P[r - l + 1]`，`l - 1` 会用到 `sum[0]`，所以数组必须从下标 0 开始有效。
6. **多组数据要重算**：`P` 与 `sum` 在每组数据前都要重新初始化，否则上一组的残留会污染本组。


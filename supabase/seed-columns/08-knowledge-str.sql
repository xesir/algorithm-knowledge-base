## 常见陷阱与注意事项

1. **下标体系（0-based vs 1-based）**
   - 本代码使用 0-based 下标，`next[0] = -1` 作为哨兵
   - 不同实现可能用 1-based（`next[0] = 0` 或 `next[1] = 0`），需注意区分
   - 匹配成功位置 `i - m + 1` 也是 0-based

2. **j = -1 的哨兵含义**
   - `j = -1` 表示模式串指针已经退到最前面，再退就没了
   - 当 `j = -1` 且失配时，主串指针 $i$ 必须前进，模式串指针重置为 0（`j++` 后为 0）

3. **匹配成功后的回退**
   - 找到一个匹配后，`j = next[j]` 而不是 `j = -1`
   - 这样做是为了支持**重叠匹配**，例如 "AAAA" 中找 "AA" 可以找到 3 个位置
   - 如果不需要重叠匹配，可以设置 `j = -1` 或根据题目要求调整

4. **while 回退的边界条件**
   - 必须写 `while (j != -1 && ...)`，不能漏 `j != -1`
   - 如果 `j = -1` 时还执行 `j = next[j]`，`next[-1]` 会越界

5. **字符串为空的边界情况**
   - 模式串为空时应直接返回所有位置（或根据题意处理）
   - 主串为空且模式串非空时无匹配
   - 本题代码中 `m = str.size()`，若 `m = 0` 则循环不执行，需注意

6. **next 数组的两种定义**
   - 定义 1（本代码）：`next[i]` 是最长相等前后缀的末尾下标（长度 - 1），`next[0] = -1`
   - 定义 2：`next[i]` 是最长相等前后缀的长度，`next[0] = 0`
   - 两种定义等价，但匹配时的比较方式不同（`p[j+1]` vs `p[j]`），不要混用


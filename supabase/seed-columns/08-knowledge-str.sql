## 复杂度分析

- **时间**：$O(n)$，$n$ 为原串长度。外层循环 $2n+1$ 轮，每轮除 `while` 外都是 $O(1)$；`while` 的总比对次数是关键——每次比对成功，$r$ 右移 1 格，$r$ 最大到 $2n+1$；每次 `while` 结束时至多一次失败比对，失败次数受循环轮数 $O(n)$ 限制。所以总时间严格 $O(n)$，而朴素中心扩展是 $O(n^2)$。
- **空间**：$O(n)$。$t$ 长 $2n+2$，$p$ 长 $2n+2$，无其他额外开销。

## 适用场景

- **单串最长回文子串**：Manacher 是线性时间的最优解，模板题直接套用（返回 `ans - 1`）。
- **回文半径数组的衍生应用**：以每个位置为中心的最长回文、回文子串计数、判断某位置是否被足够长的回文覆盖（差分前缀和技巧与 $p$ 数组结合）、双倍回文类问题（如洛谷 P4555）。
- **不要用**：多次询问「任意下标区间是否回文」时，预处理正反哈希 $O(1)$ 判定更合适，Manacher 只有中心信息、不便应答任意区间；字符串极短或只需要一次结果时，朴素 $O(n^2)$ 中心扩展代码更简单，Manacher 的细节多、易写错。

## 常见陷阱与注意事项

1. **返回时忘记 `-1`**：改造串半径 = 原回文长度 + 1，直接返回 `ans` 会比正确答案多 1。
2. **半径语义混淆**：$p[i]$ 含中心自身；右端下标是 $i + p[i] - 1$，不是 $i + p[i]$，`r` 更新时错一个常数会破坏镜像借用。
3. **镜像公式写错**：镜像点必须是 $j = mid \times 2 - i$；写成 $2 \times (mid - i)$ 或 $mid - (i - mid)$ 之外的形态都会借错对象。
4. **`min` 的两个参数位置/含义混淆**：第二参数是 $r - i + 1$（到已知右边界为止的可保证长度），漏了它或把它换成 $r - i$ 都会让半径越过未知区域，产生错误结果。
5. **漏左哨兵**：没有 `~` 时 `while` 向左会在 $i = p[i]$ 时访问负下标，是未定义行为；右端没有哨兵，程序依赖 `std::string` 的 `t[t.size()]` 返回 `'\0'` 的特性停住——若自己改成字符数组实现，要另加右哨兵。
6. **循环起点错**：写成 `i = 0` 会把哨兵当中心；正确起点是 `i = 1`。
7. **预处理漏掉结尾 `#`**：每个字符后接 `#` 但丢末尾一个时，偶数回文以两个字符间的 `#` 为中心仍可行，但长度奇数性质破坏、边界位缺失，容易在最后一个字符处出错——按「先放 `~#`、再逐字符 `ch + '#'`」的写法能自动补全。
8. **多组数据不重置**：$p$、$r$、$mid$、$ans$ 每次进入 `manacher` 都是局部新建的，所以单函数复用没问题；但若把 $p$ 提成全局复用数组，就要记得清空。
9. **只想要长度却拿半径当答案**：给出「以某位置为中心的回文长度」这类需求时，注意答案问的是原串长度还是含 `#` 的半径，单位不同差 1 倍左右。


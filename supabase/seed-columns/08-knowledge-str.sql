**解决的问题**：给定文本串 $s$（长度 $n$）和模式串 $t$（长度 $m$），要求出 $t$ 在 $s$ 中出现的所有位置。

最朴素的做法：枚举 $s$ 的每个起点 $i$，然后逐字符比较 $t$ 和 $s[i \dots i+m-1]$，失配就换下一个起点。复杂度 $O(nm)$，显然不可接受。

举个例子：

```
s = ABABABC
t = ABABC
```

匹配到第五个字符时失配，暴力做法会从 $s$ 的第二个位置重新开始，又从头比较 $t$。但事实上，我们已经知道 $s$ 的前四个字符是 `ABAB`，其中蕴含了大量关于 $t$ 前缀的信息，这些信息被白白浪费了。

KMP 的核心就是：**失配时，利用已经匹配过的部分，把模式串往前“滑”到一个合适的位置**。

### border

KMP 的一切都围绕一个概念展开，**border**。

一个字符串 $s$ 的 border，定义为：$s$ 的一个**非自身**的子串 $t$，满足 $t$ 既是 $s$ 的前缀，又是 $s$ 的后缀。

- `ABA` 的 border 是 `A`（长度 1），因为 `A` 既是前缀也是后缀。
- `ABAB` 的 border 是 `AB`（长度 2）。
- `ABC` 没有 border。

**为什么 border 重要？** 因为它决定了失配后能跳多远。

假设模式串 $t$ 已经和文本串匹配了前 $j$ 个字符，在第 $j+1$ 个字符失配。此时我们已经确定 $s$ 中有一段等于 $t[1 \dots j]$。如果 $t[1 \dots j]$ 有一个长度为 $k$ 的 border，那么 $t$ 的前 $k$ 个字符和 $t[j-k+1 \dots j]$ 个字符相同。这意味着：**我们可以把 $t$ 往前滑，让它的前 $k$ 个字符对齐到刚才匹配段的后 $k$ 个字符上，然后从第 $k+1$ 位继续匹配**。

而 $k$ 取最大 border 长度时，滑动的距离最短，不遗漏任何可能的匹配。

### next 数组

KMP 的核心预处理就是求出模式串 $t$ 每个前缀的**最长 border 长度**，通常记为 `nxt[i]`，表示 $t[1 \dots i]$ 的最长 border 长度。以 `ABABC` 为例：

| $i$ | 前缀 | 最长 border | `nxt[i]` |
| :---: | :---: | :---: | :---: |
| 1 | `A` | 无 | 0 |
| 2 | `AB` | 无 | 0 |
| 3 | `ABA` | `A` | 1 |
| 4 | `ABAB` | `AB` | 2 |
| 5 | `ABABC` | 无 | 0 |

注意 `nxt[1]` 恒为 0，因为单个字符不存在非自身的 border。

如何求 `nxt` 呢？只需要让**模式串自己和自己做匹配**。假设我们已经知道了 `nxt[1..i-1]`，现在要求 `nxt[i]`。设当前 `j = nxt[i-1]`，意思是 $t[1 \dots i-1]$ 的最长 border 长度为 $j$。那么 $t[1 \dots j] = t[i-j \dots i-1]$。现在看 $t[j+1]$ 和 $t[i]$ 是否相等：

- **相等**：说明 border 可以延长，`nxt[i] = j + 1`。
- **不相等**：说明当前这个 border 没法延长。但 $t[1 \dots j]$ 本身可能还有更短的 border，于是退而求其次，令 `j = nxt[j]`，继续尝试，直到 $j = 0$ 或找到匹配为止。

这个过程和匹配文本串时的失配跳转一模一样，**求 next 的过程就是模式串对自己做一遍 KMP 匹配**。

### 匹配过程

有了 `nxt` 数组，匹配就简单了。维护一个指针 $j$ 表示当前模式串匹配到了第几位：

- 如果 $t[j+1] = s[i]$，$j$ 往后走一位；
- 如果失配，令 $j = nxt[j]$，即把模式串往前滑到下一个可能的对齐位置；
- 如果 $j = m$，说明模式串完整出现了一次，记录位置，然后令 $j = nxt[m]$ 继续找下一次匹配。

## 核心公式 / 状态定义与转移方程

状态定义：

- `nxt[i]`：$t[1 \dots i]$ 的最长 border 长度，取值范围 $[0, i-1]$。
- 匹配过程中 $j$：当前模式串已匹配的长度，取值恒在 $[0, m]$ 内。

转移（$j_0 = nxt[i-1]$）：

$$
nxt[i] =
\begin{cases}
j + 1, & t[j+1] = t[i],\ j = j_0 \text{ 或 } j \text{ 回退后成立} \\
0, & j \text{ 已回退到 } 0 \text{ 且 } t[1] \ne t[i]
\end{cases}
$$

其中回退规则是 $j \leftarrow nxt[j]$（只要 $j > 0$ 且 $t[j+1] \ne t[i]$ 就一直退）。

匹配过程的转移：主串指针 $i$ 从 $1$ 到 $n$ 单向前进；失配时 $j \leftarrow nxt[j]$；$j$ 达到 $m$ 时输出 $i-m+1$，并令 $j \leftarrow nxt[m]$。


Sunday 算法由 Daniel M. Sunday 于 1990 年提出，是一种高效的字符串匹配算法。它的核心思想是：**当匹配失败时，关注主串中当前窗口的下一个字符，根据该字符在模式串中的位置来决定模式串向右移动多少位**。

与 KMP 相比，Sunday 算法代码更简洁，在实际应用中往往比 KMP 更快（尤其在字符集较大、模式串较短时），但其最坏时间复杂度为 $O(nm)$，而 KMP 最坏仍是 $O(n+m)$。

### 核心思想

假设主串为 $s$（长度 $n$），模式串为 $p$（长度 $m$）：

1. 从左到右将模式串与主串当前窗口对齐比较
2. 如果匹配成功，记录起始位置
3. 如果匹配失败，看**主串中当前窗口右边的第一个字符**（即 $s[i+m]$）：
   - 如果这个字符**在模式串中出现过**，就把模式串右移，让模式串中最右边的该字符与主串中的该字符对齐
   - 如果这个字符**不在模式串中**，直接把模式串右移 $m+1$ 位（跳过这个不可能匹配的字符）

### 为什么高效

Sunday 算法每次移动的步长通常比 KMP 更大，尤其当模式串中字符不重复时，平均每次可以移动很多位，因此实际运行很快。

## 偏移表（next 数组）

Sunday 算法需要预处理一个**偏移表**（也叫 shift 表或 next 数组），记录每个字符对应的移动步数：

$$
\text{next}[c] =
\begin{cases}
m - \text{pos}(c) & \text{若 } c \text{ 在模式串中出现，pos}(c) \text{ 是最右出现位置} \\
m + 1 & \text{若 } c \text{ 不在模式串中}
\end{cases}
$$

其中 $m$ 是模式串长度。

### 偏移表示例

以模式串 `p = "abcab"` 为例（$m = 5$）：

| 字符 | 最右位置 | next 值（移动步数） |
|------|---------|-------------------|
| a | 3 | 5 - 3 = 2 |
| b | 4 | 5 - 4 = 1 |
| c | 2 | 5 - 2 = 3 |
| 其他 | - | 5 + 1 = 6 |

解释：
- 如果窗口右边的字符是 `a`，模式串右移 2 位（让模式串最右的 `a` 对齐）
- 如果窗口右边的字符是 `b`，模式串右移 1 位
- 如果窗口右边的字符是 `z`，模式串直接右移 6 位

## 算法步骤

1. **预处理偏移表**：遍历模式串，记录每个字符最右边的出现位置，计算每个字符对应的移动步数
2. **匹配过程**：
   - 主串指针 $i = 0$
   - 当 $i \le n - m$ 时：
     - 比较 $s[i..i+m-1]$ 与 $p[0..m-1]$
     - 若完全匹配：记录位置 $i$，然后继续找下一个
     - 若不匹配且 $i + m < n$：$i \mathrel{+}= \text{next}[s[i+m]]$
     - 若不匹配且 $i + m \ge n$：结束


```

其中 $j = mid \times 2 - i$ 是 $i$ 关于 $mid$ 的镜像点。$p[j]$ 是镜像处的已知半径；$r-i+1$ 是「不超过已知右边界」时能保证的最大半径。两者取小：镜像回文太短则全盘继承（情况 A），镜像回文超出已知范围则只能继承到 $r$ 为止（情况 B）。

2. 扩展：`while (t[i - p[i]] == t[i + p[i]]) ++p[i];` —— 在保底之上比对未知区域，直到失配或碰到哨兵。

3. 更新：若 `p[i] + i > r`，说明找到了更靠右的回文，令 `r = p[i] + i - 1`、`mid = i`。

4. 答案：`ans = max(ans, p[i])`，最终返回 `ans - 1`。

**手算示例**：$s = \verb|aba|$，改造后 $t = \verb|~#a#b#a#|$，下标 $0 \sim 7$。

| 中心 i | 初始 p[i]（min 保底） | while 扩展 | 最终 p[i] | r / mid 更新 |
|---|---|---|---|---|
| 1 | 0（i > r） | t[1] 与自身相等 → 1，t[0]='~' 与 t[2]='a' 失配 | 1 | r=1, mid=1 |
| 2 | 0（i > r） | t[1]='#'==t[3]='#' → 2，t[0]='~' 与 t[4]='b' 失配 | 2 | r=3, mid=2 |
| 3 | min(p[1], 1)=1 | t[2]='a' 与 t[4]='b' 失配 | 1 | r=4, mid=3 |
| 4 | min(p[2], 1)=1 | t[3]=t[5]→2，t[2]=t[6]→3，t[1]=t[7]→4，t[0]='~' 与 t[8] 失配 | 4 | r=7, mid=4 |
| 5 | min(p[3], 3)=1 | t[4]='b' 与 t[6]='a' 失配 | 1 | 无 |
| 6 | min(p[2], 2)=2 | t[4]='b' 与 t[8] 失配 | 2 | 无 |
| 7 | min(p[1], 1)=1 | t[6]='a' 与 t[8] 失配 | 1 | 无 |


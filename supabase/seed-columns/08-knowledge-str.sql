字符串 $S$ 的循环同构串是将 $S$ 在某个位置断开并重新拼接得到的串。例如 $S = \text{"bcad"}$ 的循环同构串有 "bcad"、"cadb"、"adbc"、"dbca" 共 4 种。最小表示法的目标是找出所有循环同构串中字典序最小的那一个。朴素做法是枚举 $n$ 个起点逐字符比较，时间复杂度为 $O(n^2)$，在 $n$ 较大时不可接受。

最小表示法采用双指针 $i$、$j$ 分别表示两个候选起点，维护一个匹配长度 $k$。每轮比较从 $i$ 和 $j$ 出发的同构串的第 $k$ 个字符：若 $S[i+k] \ne S[j+k]$，则字典序较大那一侧的起点及其后的 $k$ 个位置都不可能成为最优起点，可直接跳过。具体地，若 $S[i+k] > S[j+k]$，则起点 $i, i+1, \ldots, i+k$ 均被排除，令 $i = i + k + 1$；反之令 $j = j + k + 1$。这种"批量跳过"策略是算法达到 $O(n)$ 的核心。

跳跃正确性的关键在于：若从起点 $i$ 出发的串在第 $k$ 位劣于从 $j$ 出发的串，那么对于任意 $i' \in [i, i+k]$，从 $i'$ 出发的串在第 $(i+k-i')$ 位恰好对应原 $S[i+k]$ 的字符（循环同构性质），因此 $i'$ 也一定劣于从 $j + (i'-i)$ 出发的串，无需再比较。为保证 $i \ne j$，当跳跃后两者相等时将其中一个加一错开。当 $k$ 达到 $n$ 时说明两个候选起点出发的串完全相同（整串存在周期 $|i-j|$），此时任一候选都是最小表示，直接跳出循环并返回 $\min(i,j)$。

## 核心公式

循环同构串定义（在位置 $i$ 断开）：
$$T_i = S[i..n] + S[1..i-1]$$

最小表示的目标：
$$\text{ans} = \arg\min_{0 \le i < n} T_i$$

双指针比较与跳跃规则（设 $k$ 为已匹配长度）：
$$\text{if } S[i+k] > S[j+k] \text{ then } i \leftarrow i+k+1, \quad \text{else } j \leftarrow j+k+1$$

跳跃排除的不等式（$S[i+k] > S[j+k]$ 时对任意 $d \in [0, k]$）：
$$T_{i+d} > T_{j+d}$$

最终结果取较小指针：
$$\text{ans} = \min(i, j)$$


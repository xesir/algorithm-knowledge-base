## 复杂度分析

- **求 `nxt`**：$i$ 单调递增 $m$ 次；`j` 每次回退至少减小 1，而每轮循环 `j` 最多加 1，所以 `while` 的总回退次数不超过 $m$，均摊 $O(m)$。
- **匹配**：同理，`i` 前进 $n$ 次，`j` 的回退总次数不超过 $n$，均摊 $O(n)$。
- **总时间**：$O(n + m)$，严格线性，没有 $\log$，也不会像哈希那样被构造数据卡。
- **空间**：只需一个 `nxt` 数组，$O(m)$。

## 适用场景

- **单模式串匹配**：求出现位置、出现次数、第一次出现的位置。
- **求最短循环节 / 周期**：若 $n - nxt[n]$ 能整除 $n$，则 $n - nxt[n]$ 就是最小循环节长度。
- **枚举所有 border**：从 `nxt[n]` 出发沿 `nxt` 链一直跳，得到的每个前缀都是整个串的 border。
- **统计前缀出现次数**：在 `nxt` 树上做一遍子树和。
- **作为更复杂算法的前置**：AC 自动机的 fail 指针、扩展 KMP、Z 函数都建立在同一套「失配后跳到最长 border」的思想上。

## 常见陷阱与注意事项

1. **下标从 0 还是从 1**：本模板全程 1-indexed（`t[1..m]`、`nxt[1..m]`）。若字符串用 0-indexed 存，必须整体平移一位，两套写法混用是 KMP 最常见的错源。
2. **`while` 忘了判 `j`**：`while (t[j + 1] != t[i]) j = nxt[j];` 在 `j = 0` 且 `t[1] != t[i]` 时会死循环 / 越界。必须写成 `while (j && ...)`。
3. **求 `nxt` 的循环从 `i = 2` 开始**：从 1 开始会把 `nxt[1]` 算成错误值。
4. **匹配成功后 `j = nxt[m]` 而不是 0**：写 0 会漏掉重叠的匹配。
5. **比较的下标**：是 `t[j + 1]` 与 `t[i]` / `s[i]`，写成 `t[j]` 全盘皆错。
6. **`nxt` 数组开小**：`nxt` 的大小是模式串长度 $m$，别按文本串长度开。
7. **多组数据忘记重置**：`nxt` 每换一个模式串都要重新求，不能复用上一组的值。


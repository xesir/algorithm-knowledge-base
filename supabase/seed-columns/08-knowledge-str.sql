	void build(){
		queue<int> q;
		for(int i=0;i<26;i++){
			if(c[rot][i]){
				fail[c[rot][i]]=rot;
				q.push(c[rot][i]);
				ind[rot]++;
			}
		}
		while(q.size()){
			int x=q.front();q.pop();
			for(int i=0;i<26;i++){
				if(c[x][i]){
					fail[c[x][i]]=c[fail[x]][i];
					q.push(c[x][i]);
					ind[fail[c[x][i]]]++;
				}else c[x][i]=c[fail[x]][i];
			}
		}
	}

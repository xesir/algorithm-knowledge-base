int manacher(const string& s)
{
	string t = "~#";
	t.reserve(s.size() * 2 + 2);
	for (char ch : s)
	{
		t += ch;
		t += '#';
	}

```

- `t = "~#"`：`~` 是左哨兵，`#` 是第一个分隔符。
- `reserve(s.size() * 2 + 2)`：改造后长度正好是 $2n+2$，一次分配避免 `+=` 反复扩容。
- 循环里每个字符后接一个 `#`：`s[0]#s[1]#...#`，保证每个原字符右侧都有一个分隔符，且整串长度恒为奇数。

### 模块 2 核心循环

```cpp
	int r = 0, mid = 0, ans = 0;
	vector<int> p(t.size(), 0);
	for (int i = 1; i < t.size(); i++)
	{
		if (i <= r) p[i] = min(p[mid * 2 - i], r - i + 1);
		while (t[i - p[i]] == t[i + p[i]]) ++p[i];
		if (p[i] + i > r)
		{
			r = p[i] + i - 1;
			mid = i;
		}
		ans = max(ans, p[i]);
	}
	return ans - 1;
}
```

- 循环从 $i=1$ 开始：下标 0 是哨兵，不可能作为回文中心，跳过。
- `if (i <= r)` 是「能否借历史信息」的分界：$i$ 在已知最右回文内部才能用镜像保底，否则 $p[i]$ 保持 0 从零暴力扩展。
- `p[mid * 2 - i]` 计算镜像点 $j$：由 $i - mid = mid - j$ 推出 $j = 2 \times mid - i$。
- `r - i + 1` 把保底限制在已知边界内：$i$ 在 $r$ 内的部分关于 $mid$ 必然对称，越出 $r$ 的部分没有任何保证。
- `while (t[i - p[i]] == t[i + p[i]])`：向左向右各看一格；左侧最终碰到 `~` 失配，右侧最终碰到串尾的 `'\0'` 失配，天然终止，无需手写边界判断。
- `r = p[i] + i - 1`：注意减一。$p[i]$ 是含中心的半径，右端下标 = 中心 + 半径 − 1。
- 返回 `ans - 1`：改造串半径到原串长度的换算（含中心的半径比原回文长度多 1）。


## 复杂度分析

看起来有一个 while 循环在暴力扩展，但实际上**每个字符最多被扩展一次**——因为每次扩展都会把 $R$ 向右推，而 $R$ 只增不减，最多从 0 推到 $2n+1$。

所以总复杂度是 $O(n)$，线性的。

细化一下这个均摊：当 $i \ge R$ 时，`p[i]` 从 0 起，每次 while 成功都会让 `i + p[i]` 越过原来的 $R$；当 $i < R$ 时，继承来的半径已经把 $[i-p[i],\ i+p[i]]$ 这一段盖住了，while 若还能成功，只能发生在 $R$ 之外，同样推着 $R$ 往右走。$R$ 单调右移、总位移 $O(n)$，所以 while 的成功次数是 $O(n)$；每次失败比对对应一轮循环，也是 $O(n)$。总时间 $O(n)$。

**空间**：展开串 `t` 长 $2n+1$，半径数组 `p` 长 $2n+1$，都是 $O(n)$，没有别的辅助结构。


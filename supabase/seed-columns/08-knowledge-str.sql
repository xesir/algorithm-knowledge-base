## 复杂度分析

时间复杂度：主循环中虽然存在 `while` 暴力扩展，但每次扩展都会把 $R$ 向右推进至少一位，而 $R$ 单调不减、最多从 0 推到 $m-1$（展开串长度 $m = 2n+1$），因此所有 `while` 扩展的**总次数**为 $O(m) = O(n)$。整体时间复杂度为 $O(n)$。

空间复杂度：需要存储展开串 $t$（$O(n)$）与半径数组 $p$（$O(n)$），总空间复杂度为 $O(n)$。

## 适用场景

1. **最长回文子串**：直接取 $\max_i p[i]$，是 Manacher 最经典的应用。
2. **回文子串个数**：以每个中心 $i$ 为对称轴的回文子串个数为 $\lceil p[i]/2 \rceil$，求和 $\sum \lceil p[i]/2 \rceil$ 即可。
3. **回文串判定**：结合哈希可在 $O(1)$ 内判断任意子串是否回文，但求全局最长回文时 Manacher 更合适。
4. **双倍回文（P4555）**：在 Manacher 的基础上增加预处理，求两个相邻回文串拼接而成的最长"双倍回文"。

## 常见陷阱与注意事项

1. **分隔符不能与输入字符冲突**：本实现用 `#` 作分隔符，隐含假设输入串不含 `#`（如输入限定为小写字母）。若输入可能出现 `#`，需改用其他不冲突的哨兵字符。
2. **$p[i]$ 的含义**：它是"不含中心"的半径，且恰好等于原串对应回文子串的长度，直接取 $\max$ 即为答案，不要再做 $(2p[i]+1)/2$ 这类换算。
3. **镜像继承必须带 $R-i$ 上限**：继承量是 $\min(p[2C-i], R-i)$，漏掉 `R - i` 会把"超出当前最右回文串范围"的部分误判为已知回文。
4. **暴力扩展的边界**：`while` 条件必须同时检查 `i - p[i] - 1 >= 0` 与 `i + p[i] + 1 < m`，否则首尾越界。
5. **展开串下标与长度**：展开后长度 $m = 2n+1$，`p` 数组也要开成 $m$ 大小；循环遍历范围是 `i < m` 而非 `i < n`。
6. **`ans` 的更新**：输出的是最大半径 $p[i]$（即原回文长度），而非展开串的回文长度 $2p[i]+1$。


KMP（Knuth-Morris-Pratt）算法是一种高效的字符串匹配算法，用于在文本串（主串）$s$ 中查找模式串（子串）$p$ 的所有出现位置。

### 朴素匹配的问题

朴素（暴力）匹配：对主串的每个起始位置尝试与模式串逐位比较，失配后主串指针回退、模式串指针归零。最坏情况下时间复杂度为 $O(n \cdot m)$，当两个串都很长且有大量部分匹配时效率极低。

KMP 的核心思想：**利用已匹配的信息，避免主串指针回退**。当发生失配时，根据模式串自身的前后缀公共信息，将模式串"跳"到合适的位置继续匹配，主串指针 $i$ 始终只前进不后退。

### next 数组（前缀函数）

KMP 的关键是预处理模式串，得到一个 `next` 数组（也叫前缀函数 / failure function）。

**定义**：`next[i]` 表示模式串 $p[0 \dots i]$ 中，最长相等前缀和后缀的长度（严格小于子串长度）。换句话说，`next[i] = j` 意味着 $p[0 \dots j] = p[i-j \dots i]$，且这是满足条件的最大 $j$。

本代码实现中，`next[0] = -1`（哨兵值，表示已经退无可退，主串指针需要前进一位），其余位置 `next[i]` 表示的是"最长相等前后缀的末尾下标"（即长度 $-1$）。

### 匹配过程

设主串指针为 $i$（遍历主串），模式串指针为 $j$（当前已匹配到模式串的第 $j$ 位）：

1. 若 $j = -1$ 或 $s[i] = p[j+1]$，则 $i$ 前进一位，$j$ 前进一位
2. 若 $s[i] \neq p[j+1]$，则 $j = \text{next}[j]$（模式串"回退"到最长可匹配前缀的位置）
3. 当 $j = m-1$（模式串末尾）时，说明找到了一次匹配，记录位置后继续 `j = next[j]` 寻找下一个

整个匹配过程中主串指针 $i$ 只增不减，因此匹配阶段时间复杂度为 $O(n)$。


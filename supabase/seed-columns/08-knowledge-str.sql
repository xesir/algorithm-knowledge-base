{
    kmp_next.clear();
    int m = str.size(), j = -1;
    kmp_next.resize(m, -1);
    for (int i = 1; i < m; i++)
    {
        while (j != -1 && str[i] != str[j + 1]) j = kmp_next[j];
        if (str[i] == str[j + 1]) j++;
        kmp_next[i] = j;
    }
}
```

`next` 数组的计算本身就是一个"自己匹配自己"的 KMP 过程。$i$ 遍历模式串（从 1 开始，因为 `next[0]=-1` 已知），$j$ 表示当前已匹配的前缀末尾下标。每一步：
- 如果当前字符不匹配，就用 `next` 数组回退 $j$
- 如果匹配，$j$ 前进一位
- 将 $j$ 记录为 `next[i]`

### KMP 匹配过程

```cpp
void kmp(const string& a, const string& b)
{

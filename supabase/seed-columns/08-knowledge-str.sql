Manacher 算法用于求解**最长回文子串**：给定一个字符串 $s$，求它的最长连续回文子串。

回文串分为两类：**奇数长度**（中心是单个字符，如 `aba`）和**偶数长度**（中心在两个字符之间，如 `abba`）。为了统一处理，先在字符串每两个字符之间以及两端插入分隔符 `#`，例如 `abba` 变为 `#a#b#b#a#`。这样每个对称中心都会对应到一个具体的字符位置，所有回文都被转化为奇数长度，便于统一扩展。

朴素做法是枚举每个可能的中心，向两侧逐位扩展直到失配，复杂度为 $O(n^2)$。其低效之处在于：**每个中心都从头开始扩展，大量已计算过的回文信息被重复利用**，例如 `aaaaa` 每个中心都要完整扩展一遍，总扩展次数达到 $O(n^2)$。

Manacher 的优化核心是：**利用已经找到的回文串的对称性，避免重复扩展**。维护"右端点最靠右"的已知回文串，在处理新中心时先通过对称关系"继承"一部分回文半径，再只对可能扩展的部分暴力扩展，从而把总复杂度降到线性。

## 核心公式 / 状态定义与转移方程

定义 $p[i]$ 为：**以位置 $i$ 为中心的最长回文串的半径（不含中心本身）**。对展开后的串 `#a#b#b#a#`：

| $i$ | 0 | 1 | 2 | 3 | 4 | 5 | 6 | 7 | 8 |
| :---: | :---: | :---: | :---: | :---: | :---: | :---: | :---: | :---: | :---: |
| 字符 | `#` | `a` | `#` | `b` | `#` | `b` | `#` | `a` | `#` |
| $p[i]$ | 0 | 1 | 0 | 1 | 4 | 1 | 0 | 1 | 0 |

以 $i=4$ 为中心，回文串是整个 `#a#b#b#a#`，半径 $p[4]=4$。

**关键转化**：在带 `#` 的展开串中，以 $i$ 为中心的最长回文半径 $p[i]$ 恰好等于**原串中对应的最长回文子串长度**。因此原串最长回文子串的长度等于 $\max_i p[i]$。

**镜像继承**：维护两个变量

- $C$：当前已知回文串中**右端点最靠右**的那个回文串的中心；
- $R$：该回文串的右端点，即 $R = C + p[C]$。

处理位置 $i$ 时，若 $i < R$，则 $i$ 落在当前最右回文串的覆盖范围内，其关于 $C$ 的对称点为 $i' = 2C - i$。由回文串的对称性，$p[i]$ 至少可以继承 $p[i']$ 的一部分：

$$
p[i] \ge \min(p[i'],\ R - i)
$$

由于 $p[i']$ 可能超出当前回文串的右边界，超出部分无法保证对称，故取 $\min$。于是 Manacher 的流程为：

1. 若 $i < R$，令 $p[i] = \min(p[2C-i],\ R-i)$；否则 $p[i] = 0$。
2. **暴力扩展**：从 $p[i]+1$ 开始向两侧扩展，直到两侧字符不相等或越界。
3. 更新 $C$、$R$：若 $i + p[i] > R$，令 $C = i$、$R = i + p[i]$。
4. 用 $p[i]$ 更新答案的最大值。


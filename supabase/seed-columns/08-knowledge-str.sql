字符串哈希的核心思想极其朴素：**把一个字符串映射成一个整数，用整数比较代替字符串比较。**

最常用的哈希方式是**多项式哈希**。把一个字符串看作一个 $B$ 进制数：

$$
\text{hash}(s) = \sum_{i=1}^{n} s_i \cdot B^{\,n-i} \pmod{M}
$$

其中 $s_i$ 是字符的编码（比如 `a` 对应 1，`b` 对应 2），$B$ 是进制基数（通常取一个较大的质数），$M$ 是模数。

举个例子，对于字符串 `abc`，设 `a=1, b=2, c=3`，$B=131$，那么：

$$
\text{hash}(\texttt{abc}) = 1 \times 131^2 + 2 \times 131 + 3
$$

再对 $M$ 取模。这就是它的哈希值。

这样构造的哈希函数满足一个关键性质：**前缀哈希可以递推**。设 $H[i]$ 表示前 $i$ 个字符的哈希值，则：

$$
H[i] = H[i-1] \cdot B + s_i \pmod{M}
$$

这样预处理一遍，就能在 $O(1)$ 时间内得到任意前缀的哈希值。有了前缀哈希，任意子串 $s[l \dots r]$ 的哈希值也能 $O(1)$ 算出来：

$$
\text{hash}(l, r) = H[r] - H[l-1] \cdot B^{\,r-l+1} \pmod{M}
$$

所以字符哈希复杂度是预处理 $O(n)$，之后每次子串比较都是 $O(1)$。

当然，字符哈希显然也会冲突。一般我们直接开 `unsigned long long` 自然溢出，防卡也可以用双哈希。

## 核心公式 / 状态定义与转移方程

记字符串为 $s[1 \dots n]$，$s_i$ 为字符编码（建议从 1 开始，不要用 0），$B$ 为基数，$M$ 为模数。

- **哈希定义**（把串当 $B$ 进制数）：

$$
\text{hash}(s) = \sum_{i=1}^{n} s_i \cdot B^{\,n-i} \bmod M
$$

- **前缀哈希递推**（$H[0] = 0$）：

$$
H[i] = (H[i-1] \cdot B + s_i) \bmod M
$$

- **子串哈希**（$l \le r$，$B$ 的幂次预先用 $P[k] = B^k \bmod M$ 存好）：

$$
\text{hash}(l, r) = \left(H[r] - H[l-1] \cdot P[\,r-l+1\,]\right) \bmod M
$$

三个式子的分工：第一个是「哈希的定义」，第二个把定义改写成了可以 $O(1)$ 递推的形式，第三个是「高位对齐后相减」——把 $H[l-1]$ 左移 $r-l+1$ 位，让它与 $H[r]$ 的位权对齐，再做减法就把 $[1, l-1]$ 这一段的贡献消掉了。


## 复杂度分析

### 时间复杂度

| 操作 | 复杂度 | 说明 |
|---|---|---|
| 求 next 数组 | $O(m)$ | 双重循环看似 $O(m^2)$，实际 j 的增加次数与回退次数均不超过 $m$ |
| KMP 匹配 | $O(n)$ | i 只增不减（$n$ 次），j 的总增加量不超过 $n$，总回退量也不超过 $n$ |
| 总体 | $O(n + m)$ | 线性时间，与朴素匹配的 $O(n \cdot m)$ 形成鲜明对比 |

**为什么是线性的？** 关键观察：$j$ 每次至少增加 1（`j++`），每次回退至少减少 1（`j = next[j]`）。整个过程中 $j$ 的总增量不超过 $n$（或 $m$），因此总回退量也不超过总增量，while 循环总执行次数为 $O(n)$。

### 空间复杂度

| 数据 | 空间 | 说明 |
|---|---|---|
| next 数组 | $O(m)$ | 长度等于模式串长度 |
| ans 数组 | $O(k)$ | 匹配次数，最坏 $O(n)$ |
| **总计** | $O(m)$ | next 数组占主导（不计结果存储） |


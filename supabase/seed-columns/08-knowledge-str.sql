## 复杂度分析

### 时间复杂度

- **预处理**：$O(m)$ — 遍历模式串一次
- **匹配**：
  - **平均情况**：$O(n/m)$ — 每次平均移动 $m/2$ 位左右，总比较次数很少
  - **最坏情况**：$O(nm)$ — 例如主串全是 `a`，模式串是 `aaaaab`，每次只能移动 1 位，且每次比较到最后才失败
- **实际表现**：在随机数据下，Sunday 通常比 KMP、Boyer-Moore 都快

### 空间复杂度

- $O(|\Sigma|)$ — 偏移表大小等于字符集大小（ASCII 为 128）
- 与模式串长度无关


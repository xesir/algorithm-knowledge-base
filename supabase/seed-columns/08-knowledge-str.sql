**一句话结论**：Manacher（马拉车）通过一次「插 #」预处理把奇偶回文统一成奇数回文，再借助「已探明的最右回文」的对称性给每个中心一个保底半径，只在未知区域暴力扩展，从而在线性时间内求出最长回文子串。

**解决的问题**：给定字符串 $s$，求它的最长连续回文子串长度。

**奇偶回文的痛点**：回文串的中心有两种形态——奇数回文（如 `aba`）中心是一个字符，偶数回文（如 `abba`）中心是两个字符之间的空隙。如果直接遍历中心，就要分两种情况写代码。预处理就是为了消灭这种分支。

**预处理（统一化）**：在每个字符之间以及两端插入特殊字符 `#`：`123456` 变成 `#1#2#3#4#5#6#`。改造后有三个关键性质：

1. 无论原串奇偶，改造后的串长度恒为 $2n+1$（奇数），所有回文的中心一定落在某个具体字符上；
2. 若以第 $j$ 位为中心的回文半径为 $p[j]$（含中心自身），则对应的原串回文长度为 $p[j] - 1$，所以最后答案是 $\max p[j] - 1$；
3. 原串的每个奇数/偶数回文都与改造串的某个中心一一对应，信息没有丢失。

**哨兵**：代码把改造串写成 `t = "~#" + s 的插井号版本`，最前面的 `~` 是哨兵——它不在原串中出现，`while` 向左扩展碰到它就必然失配，省掉左侧越界判断。右侧没有哨兵，但依靠 `std::string` 在 `operator[]` 取 `pos == size()` 时返回 `'\0'` 这一特性自然停住（`'\0'` 与任何实际字符都不相等）。

**核心思想（线性时间怎么来的）**：维护「目前已探明的最右回文」——右端下标 $r$ 及其中心 $mid$。处理新中心 $i$ 时：

- 若 $i \le r$，则 $i$ 关于 $mid$ 的镜像点 $j = 2 \times mid - i$ 已经算过了。由对称性，$i$ 的回文半径至少有 $p[j]$ 起步；但借来的信息不能越过右边界 $r$，所以保底值是 $\min(p[j], r - i + 1)$。
- 在此保底之上，`while` 只对「真正未知」的区域一左一右暴力比对。
- 每次 `while` 比对成功，$r$ 就右移一格；$r$ 只增不减、最多移动到串尾，所以全程比对总次数是 $O(n)$，其余操作每轮 $O(1)$。

**为什么这样做是对的**：不变量是「$[mid - (p[mid]-1),\ r]$ 这一段关于 $mid$ 对称，且 $r$ 是已探明回文的最右端」。当 $i \le r$ 时，把 $p[j]$ 和 $r-i+1$ 取小作为起步值，得到的半径一定不超过真实半径（对称部分必然相等，只是再往外是否相等未知），因此不会漏扩；`while` 在此基础上逐格验证未知区，算出的 $p[i]$ 就是真实半径。每轮结束后若 $i + p[i] - 1 > r$，就更新 $r$、$mid$ 使不变量继续成立。归纳到底，所有 $p[i]$ 都被正确算出，$\max p[i] - 1$ 即最长回文子串长度。


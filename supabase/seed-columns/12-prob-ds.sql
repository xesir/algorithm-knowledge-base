## 解题思路

### 一、问题转化：为什么要用差分数组

原题的操作是"选区间 $[l, r]$，把里面所有数整体 $+1$ 或 $-1$"。如果直接在原数组上思考，每次操作影响的是一整段，状态空间非常大。但目标是"最终所有数都相等"，即只关心"相邻元素的相对差异是否归零"——这正是差分数组擅长的场景。

构造差分数组：

$$b[i] = a[i] - a[i-1] \quad (i = 2, \ldots, n), \quad b[1] = a[1]$$

则原数组 $a$ 可以由 $b$ 的前缀和唯一还原。在此对应下：

$$\text{所有数相等} \iff b[2 \ldots n] \text{ 全部为 } 0$$

而 $b[1]$ 的值就是那个相等的最终值。

一次区间操作 $[l, r]$ 加 $1$，在差分数组上等价于：$b[l] \mathrel{+}= 1$ 且 $b[r+1] \mathrel{-}= 1$；减 $1$ 则符号相反。也就是说，每一次区间操作，本质上是在差分数组上挑选两个位置，一个 $+1$、另一个 $-1$。

约定 $b[n+1]$ 是一个虚拟的、不影响答案的位置，对应 $r = n$ 的情形。因此每次操作等价于选择一对位置 $(i, j)$（$i, j \in [1, n+1]$），使 $b[i]$ 加 $1$、$b[j]$ 减 $1$（或反之）。

### 二、操作分类：四种配对方式

把每次操作按其作用的位置分类：

| 操作类型 | 作用位置 | 对 $b[2 \ldots n]$ 的影响 | 对最终值 $b[1]$ 的影响 |
|---|---|---|---|
| ① 内部配对 | $b[i]$ 与 $b[j]$，$2 \le i, j \le n$ | 一正一负同时向 $0$ 靠拢 | 不影响 |
| ② 与首项配对 | $b[1]$ 与 $b[i]$，$2 \le i \le n$ | 消掉一个正/负数 | 会改变 $b[1]$ |
| ③ 与尾部配对 | $b[i]$ 与 $b[n+1]$，$2 \le i \le n$ | 消掉一个正/负数 | 不影响 |
| ④ 首尾配对 | $b[1]$ 与 $b[n+1]$ | 无效操作 | 无意义 |

类型 ④ 是浪费，应当完全避免；类型 ① 是最高效的（一次操作同时让一个正数和一个负数各走一步）；类型 ② 和 ③ 都只能消掉一个数，但类型 ② 会改变最终的 $b[1]$。

### 三、第一问：最少操作次数

设 $b[2 \ldots n]$ 中：

- $pos$ = 所有正数之和
- $neg$ = 所有负数的绝对值之和

由于每一步操作（无论哪种类型）最多只能让"正数总和"减少 $1$，同时让"负数绝对值总和"减少 $1$（或单独让其中一边减少 $1$），因此有下界：

$$\text{最少次数} \ge \max(pos, neg)$$

而这个下界是可以达到的：

1. 先用 $\min(pos, neg)$ 次"类型 ①"操作：每次挑一个正数和一个负数，同时各 $-1$。做完后，正负两堆中必有一堆被清空，另一堆还剩下 $|pos - neg|$ 的总量。
2. 再用 $|pos - neg|$ 次"类型 ②/③"操作：剩下的全正（或全负）的数，逐个用 $b[1]$（或 $b[n+1]$）来配对消去。

因此：

$$\text{最少操作次数} = \min(pos, neg) + |pos - neg| = \max(pos, neg)$$

### 四、第二问：最少次数下的方案数

最少总次数为 $\max(pos, neg)$ 已经定死，但操作 ① 与操作 ②/③ 的具体分配是自由的，这正是方案数的来源。

关键观察：设最后使用了 $k$ 次"类型 ②"操作（即和 $b[1]$ 配对的次数），那么 $0 \le k \le |pos - neg|$。每次"类型 ②"操作都会使 $b[1]$ 加 $1$ 或减 $1$（取决于消的是正数还是负数），因此最终的 $b[1]$ 相对初始 $b[1]$ 偏移了某个与 $k$ 相关的量。

- 当 $k = 0$ 时，$b[1]$ 不变，得到一种结果；
- 当 $k = 1, 2, \ldots, |pos - neg|$ 时，$b[1]$ 取到 $|pos - neg| + 1$ 个互不相同的值。

不同的 $k$ 一定对应不同的最终序列（$b[1]$ 不同即序列不同），所以方案数就是 $k$ 的取值个数：

$$\text{方案数} = |pos - neg| + 1$$

### 五、样例验证

以样例 $a = [1, 1, 2, 2]$ 为例：

构造差分：$b[1] = 1$，$b[2] = a_2 - a_1 = 0$，$b[3] = a_3 - a_2 = 1$，$b[4] = a_4 - a_3 = 0$，即 $b = [1, 0, 1, 0]$。

考察 $b[2 \ldots n] = [0, 1, 0]$：正数和 $pos = 1$，负数绝对值和 $neg = 0$。

- 第一问：$\max(pos, neg) = 1$。
- 第二问：$|pos - neg| + 1 = 2$。

与样例输出 $1$ 和 $2$ 完全吻合。

### 六、思路总结

整道题的解题链条可以浓缩为四步：

1. **转换视角**：区间 $\pm 1$ $\to$ 差分数组两单点 $\pm 1$；
2. **明确目标**：所有数相等 $\iff$ $b[2 \ldots n]$ 全 $0$，$b[1]$ 即为最终公共值；
3. **贪心求解**：优先做"正负配对"消去 $\min(pos, neg)$，剩余 $|pos - neg|$ 用 $b[1]$ 或 $b[n+1]$ 兜底，总次数 $\max(pos, neg)$；
4. **计数**：剩余操作中分给 $b[1]$ 的次数 $k$ 有 $|pos - neg| + 1$ 种取法，每种对应不同最终序列。

核心模型：看到"区间整体加减 $+$ 关心相邻元素关系"的组合，第一时间应该想到差分——把区间操作降维成单点操作，往往能让一个看似复杂的问题瞬间变成简单的贪心计数题。


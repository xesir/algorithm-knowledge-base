|------|------|------|
| `count[v]`（已前缀和） | 全体 0 中 $d \le v$ 的根数 | $O(1)$ 知道水位下没顶多少根 |
| `A[0 \ldots \text{cnt0}]` | $A[0] = 0$ 哨兵，$A[1 \ldots \text{cnt0}]$ 为 $d$ 原值 | 按下标取单值（注意它不做前缀和！） |

### 6. `if (ct > 0)` 和 `if (A[idx] - lazy1 > 0)` 是冗余保险

$\text{inv} > 0$ 时必有 $\text{ct} > 0$（正向）和 $A[\text{idx}] > \text{lazy1}$（反向），留着无害，作为安全冗余。


## 一、解题思路：MEX 的关键性质

$\text{mex}(C) = v$ 当且仅当：
- $0, 1, 2, \dots, v-1$ 都在 $C$ 中
- $v$ 不在 $C$ 中
- 大于 $v$ 的数是否在 $C$ 中**不影响** mex 值

这是本题最核心的出发点。我们要让 $f(B, k) = a_k$，等价于：
1. $\{0, 1, \dots, a_k-1\}$ 必须全部出现在 $\{\lfloor y/k \rfloor : y \in B\}$ 中
2. $a_k$ 一定不能出现在 $\{\lfloor y/k \rfloor : y \in B\}$ 中

---

## 二、核心思路：反向标记「禁止元素」

### 2.1 哪些数绝对不能放进 B？

如果某个数 $y$ 满足 $\lfloor y/k \rfloor = a_k$，那么 $y$ **绝对不能**放进 $B$。

原因很简单：如果 $y \in B$，那么 $a_k$ 就会出现在集合 $\{\lfloor z/k \rfloor : z \in B\}$ 中，这样 mex 就不可能等于 $a_k$ 了。

### 2.2 禁止区间

对于固定的 $k$，满足 $\lfloor y/k \rfloor = a_k$ 的所有 $y$ 构成一个连续区间：

$$a_k \le \frac{y}{k} < a_k + 1$$

$$a_k \cdot k \le y < (a_k + 1) \cdot k$$

即禁止区间为：

$$[a_k \cdot k,\ (a_k + 1) \cdot k - 1]$$

由于 $y$ 只能取 $0$ 到 $n-1$，所以实际禁止区间要与 $[0, n-1]$ 取交集：
- 若 $a_k \cdot k \ge n$，禁止区间完全在范围外，跳过
- 否则右端点截断为 $\min((a_k+1) \cdot k - 1,\ n-1)$

### 2.3 安全元素

如果某个 $y$ 对所有 $k = 1, 2, \dots, n$ 都不会产生 $a_k$（即不被任何禁止区间覆盖），那么 $y$ 就是「安全元素」，可以放心放进 $B$。

我们的构造策略：**把所有安全元素都放进 B**。

---

## 三、为什么这样构造一定正确？

题目保证原集合 $A$ 存在且合法。我们用四条引理证明构造的正确性：

### 引理 1：A 中每个元素都是安全元素

**证明**：假设 $A$ 中存在 $y$ 和某个 $k$ 使得 $\lfloor y/k \rfloor = a_k$，那么 $a_k$ 就出现在 $f(A,k)$ 的集合里，mex 就不可能是 $a_k$，与 $a_k = f(A,k)$ 矛盾。

### 引理 2：A ⊆ B

因为 $B$ 收集了所有安全元素，而 $A$ 的元素都安全，所以 $A$ 是 $B$ 的子集。

### 引理 3：B 不会产生 a_k

$B$ 中每个元素都是安全元素，安全元素对所有 $k$ 都满足 $\lfloor y/k \rfloor \neq a_k$，所以 $a_k$ 不会出现在 $f(B,k)$ 的集合中。

### 引理 4：0 到 a_k-1 都会出现在 B 产生的集合中

原集合 $A$ 满足 $f(A,k) = a_k$，所以 $0, 1, \dots, a_k-1$ 在 $A$ 中已经全部出现。又因为 $A \subseteq B$，加入更多元素不会让已出现的值消失，所以这些值仍然都出现。

**结论**：对任意 $k$，$0$ 到 $a_k-1$ 都出现，$a_k$ 不出现，所以 $\text{mex} = a_k$。构造正确。


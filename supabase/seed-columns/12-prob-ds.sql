以右指针移动为例，对于 $[l,r] \to [l,r+1]$，记 $x=a_{r+1}$，贡献即为 $x$ 在 $[l,r]$ 中产生的逆序对。设 $f(l,r,x)$ 表示这个贡献。

关键性质：$f(l,r,x)=f(1,r,x)-f(1,l-1,x)$。这种简单的差分思想在很多题里都会用到。

对于 $f(1,r,x)$，只需在莫队扫描过程中更新权值树状数组。对于 $f(1,l-1,x)$，我们首先将这样的询问放进一个 std::vector 中离线下来。


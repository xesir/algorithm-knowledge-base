    for (int i = 0; i < n; i++) {
        auto it = ms.lower_bound(1 - sum); // 找最小的 e >= 1-s
        sum += *it;                         // 落到 s+e，更新 s
        ms.erase(it);                       // 从多重集删除
        cout << sum << ' ';                 // 输出当前位置（即 a_i）
    }
    cout << '\n';
}
```

- `sum = 0`：复用变量为当前位置 $s$，初始 $0$
- `ms.lower_bound(1 - sum)`：找最小的 $e \ge 1 - s$，即"不跌破地板 1 的最负可用元素"
  - 被冻结的更小元素自动被跳过（`lower_bound` 返回第一个 $\ge$ 阈值的迭代器）
  - 之后阈值降低时又会自然被取到，无需手动管理冻结/解冻
- `sum += *it`：落点 $= s + e$，即新的 $a_i$
- **不用判空**：若所有剩余 $< \text{阈值} \le 0$，则全为负数，其和 $< \text{阈值}$，但剩余和 $= T - s \ge \text{阈值}$（因为 $T \ge 1$ 且 $s \le T$），矛盾——所以 `lower_bound` 必能找到目标


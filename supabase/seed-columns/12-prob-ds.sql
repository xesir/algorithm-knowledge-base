面积最大 $10^9 \times 10^9 = 10^{18}$，`int` 最大约 $2.1 \times 10^9$，必须用 64 位整数。

### 5.2 并查集核心

```cpp
int find(int i, vector<int>& t)
{
    if (t[i] != i)
        t[i] = find(t[i], t);   // 路径压缩
    return t[i];
}

int unity(int i, vector<int>& t, vector<int>& sz)
{
    int a_i = find(i, t);
    int b_i = find(i + 1, t);
    sz[a_i] += sz[b_i];    // 合并大小
    t[b_i] = a_i;          // 挂到左侧
    return sz[a_i];        // 返回合并后的大小
}
```

只做路径压缩，不做按秩合并。本题数据量下完全足够。

### 5.3 初始化

```cpp
void init()
{
    X.emplace_back(0);  X.emplace_back(n);   // 边界
    Y.emplace_back(0);  Y.emplace_back(m);
    op.assign(q + 1, 0);
    k.assign(q + 1, 0);
    ans.assign(q + 1, 0);
}
```

坐标数组先放入边界 $0$ 和 $n$（或 $m$），后续再追加所有切割坐标。

### 5.4 并查集初始化

```cpp
void init_t(vector<int>& t, vector<int>& sz, vector<int>& xy, int& mmax)
{
    t.assign(xy.size() + 1, 0);
    sz.assign(xy.size() + 1, 0);
    for (int i = 1; i < xy.size(); i++)
    {
        t[i] = i;
        sz[i] = xy[i] - xy[i - 1];   // 缝隙长度
        mmax = max(mmax, sz[i]);     // 初始最大间隔
    }
}
```

缝隙 $i$ 对应坐标 $xy[i-1]$ 到 $xy[i]$。此时所有切割线都存在，缝隙最细碎，max 是初始值。

### 5.5 逆序处理

```cpp
for (int i = q; i >= 1; --i)
{
    ans[i] = (unsigned long long)max_x * max_y;   // 先记录当前答案
    if (op[i] == 1)     // 纵向切割，撤销 x 方向
    {
        int idx = lower_bound(X.begin(), X.end(), k[i]) - X.begin();
        max_x = max(max_x, unity(idx, a, a_sz));
    }
    else                // 横向切割，撤销 y 方向
    {
        int idx = lower_bound(Y.begin(), Y.end(), k[i]) - Y.begin();
        max_y = max(max_y, unity(idx, b, b_sz));
    }
}
```

**关键细节**：先记录答案，再撤销操作。因为逆序循环开始时的状态对应「正序执行完第 $q$ 次操作后的状态」，记录 $ans[q]$ 后撤销第 $q$ 次操作得到第 $q-1$ 次操作后的状态，以此类推。

`lower_bound` 二分找到切割点 $k$ 在排序后坐标数组中的位置 $idx$，合并缝隙 $idx$ 和 $idx+1$。


## 解题思路

### 第一步：问题翻译——排列 + 前缀和

$b$ 打乱前的本质是：$b_1 = a_1$，后面是相邻差分。反过来看，只要把 $b$ 的 $n$ 个数排成某个顺序 $p_1, p_2, \ldots, p_n$，就唯一确定了一个还原方案：

$$a_1 = p_1, \quad a_i = a_{i-1} + p_i = \sum_{k=1}^{i} p_k$$

所以问题变成：**把多重集 $B$ 排成一个排列，使得前缀和序列 $S_1, S_2, \ldots, S_n$ 每一项都 $\ge 1$，且该序列字典序最小。**

注意 $S_0 = 0$ 不受限制（对应"还没放任何数"），但从 $S_1$ 起每一步都必须是正整数。

### 第二步：总和不变量——$-1$ 判定

不管怎么排列，全部加起来：

$$S_n = p_1 + p_2 + \cdots + p_n = \text{sum}(b) = a_n$$

终点是定死的，与排列无关。题目要求 $a_n \ge 1$，所以：

$$\text{sum}(b) \le 0 \implies \text{输出 } -1$$

例如 $b = (3, -3)$：总和 $0$，无论怎么排最后一个 $a$ 都是 $0$，不是正整数。

### 第三步：$\text{sum}(b) \ge 1$ 时一定有解（构造证明）

把所有正数放最前面，然后 $0$，最后所有负数：

- **正数阶段**：第一步落点是某个正整数 $\ge 1$，之后只升不降，全程 $\ge 1$
- **负数阶段**：位置从"正数总和 $P$"一路降到 $T = \text{sum}(b)$。负数的任意前缀部分和 $\ge$ 全体负数之和（多加一个负数只会更小），所以下降途中任何时刻的位置 $\ge T \ge 1$，永远砸不穿地板

**结论**：$-1$ 当且仅当 $\text{sum}(b) \le 0$；否则一定有解。

### 第四步：核心引理——只要还"活着"，后面永远救得回来

**引理**：从任意当前位置 $s \ge 1$ 出发，剩余任意多重集 $R$，都存在一种用完 $R$ 的方式使全程 $\ge 1$ 并恰好停在 $T$。

**证明**：第三节构造的翻版——剩余正数升序全放前面（位置只升不降，从 $s \ge 1$ 出发安全），然后 $0$，然后剩余负数（位置一路降但始终 $\ge s + \text{sum}(R) = T \ge 1$）。$\blacksquare$

这个引理是整个贪心的基石：**任何合法的前缀都可以任意延拓成完整合法方案**。做字典序贪心时永远不用担心"这一步走小了会不会把后面堵死"——不会，后面总能走完。

### 第五步：贪心策略——每一步都往"能落到的最低点"跳

维护当前位置 $s$（初始 $0$）。每一步：

1. 在剩余元素中，选**最小的满足 $s + e \ge 1$ 的 $e$**（等价于 $e \ge 1 - s$）
2. 落到 $s + e$，输出，然后 $s \mathrel{+}= e$，把 $e$ 从多重集里删掉

**正确性论证**（逐位定死 + 引理）：

- **第一位**：$S_1 = a_1$ 必须是 $B$ 中某个 $\ge 1$ 的数，最小化它就是取最小正元素；由引理，这个选择必定可以走完
- **之后每一位**：在"前缀已是当前字典序最小"的前提下，$S$ 的下一位 $= s + e$，在所有能保持 $\ge 1$ 的 $e$ 中取最小即得下一位的最小可能值；由引理，任何这样的选择都可延拓。归纳即得全局字典序最小

**直观图像**：这是一个从 $0$ 走到 $T$ 的小人，脚下有地板 $1$——

- **能往下扎就使劲扎**：每次挑最负的"踩得下去"的数（$s + e \ge 1$），一步扎到尽量深
- **快砸穿地板时垫一垫**：如果最负的剩余数会踩到 $\le 0$（它被"冻结"），就拿 $0$ 和最小的正数一点点垫高 $s$，直到那个最负的数重新踩得下去，再继续扎
- 于是负数按从小到大被消耗，正数也按升序被消耗，两类交替进行；所有数最终都会被用掉，终点恰好是 $T$

### 例子走查

**例 1**：$b = \{2, -1\}$，$\text{sum} = 1 \ge 1$

| 步 | 当前 $s$ | 阈值 $1-s$ | 可用元素 | 选择 | 落点 |
|---|---|---|---|---|---|
| 1 | 0 | 1 | 2 | 2 | 2 |
| 2 | 2 | $-1$ | $-1$ | $-1$ | 1 |

答案 $a = (2, 1)$。

**例 2**：$b = \{-5, -5, 5, 5, 6\}$，$\text{sum} = 6 \ge 1$

| 步 | 当前 $s$ | 阈值 $1-s$ | 剩余元素 | 可用 | 选择 | 落点 |
|---|---|---|---|---|---|---|
| 1 | 0 | 1 | $-5,-5,5,5,6$ | $5,5,6$ | 5 | 5 |
| 2 | 5 | $-4$ | $-5,-5,5,6$ | $5,6$ | 5 | 10 |
| 3 | 10 | $-9$ | $-5,-5,6$ | 全部 | $-5$ | 5 |
| 4 | 5 | $-4$ | $-5,6$ | 只有 6 | 6 | 11 |
| 5 | 11 | $-10$ | $-5$ | $-5$ | $-5$ | 6 |

答案 $a = (5, 10, 5, 11, 6)$。注意第 4 步：$-5$ 会让位置砸到 $0$，所以必须先垫 $6$ 把 $s$ 抬到 $11$，$-5$ 才解冻——这正是"垫一垫再扎"。


## 一、解题思路：核心观察——二维降为一维

### 1.1 切割的贯穿性

纵向切割 $x=k$ 贯穿整个高度，横向切割 $y=k$ 贯穿整个宽度。这意味着：

- 所有纵向切割线 + 左右边界 $x=0, x=n$ → 把宽度 $n$ 分成若干「宽度段」
- 所有横向切割线 + 上下边界 $y=0, y=m$ → 把高度 $m$ 分成若干「高度段」
- 任意小矩形 = 一个宽度段 $\times$ 一个高度段

### 1.2 最大面积 = max_x $\times$ max_y

**上界**：任意小矩形宽 $\le$ max_x，高 $\le$ max_y，面积 $\le$ max_x $\times$ max_y。

**可达性**：取最大宽度段对应的竖条和最大高度段对应的横条，因为所有切割线贯穿整个区域，这两个条带一定相交，交出的小矩形面积恰好 $= \text{max\_x} \times \text{max\_y}$。

因此问题拆成两个独立的一维问题：分别维护 $x$ 方向和 $y$ 方向的最大间隔长度。


## 常见陷阱与注意事项

### 1. A 不能预开 $n+1$ 个 0 再 `emplace_back`

如果写成 `vector<long long> A(n + 1, 0)` 再 `emplace_back`，数据整体错位（前面多出 $n+1$ 个无意义的 0）。正确姿势：`A(1)` 只放哨兵 $A[0] = 0$，且 `A` 不做前缀和（它要取单值）。

### 2. $d = 0$ 的 0 也要入 `count` 和 `A`

贡献虽恒为 $0$，但必须占坑，否则位置计数全错。`count[0]` 记录了 $d = 0$ 的 0 的个数，它们在水位 $0$ 时就"没顶"，但数量必须正确。

### 3. `lazy0` 只能数"拆成功"的反向操作


## 常见陷阱与注意事项

1. **做差方向必须从右往左**
   - 若从左往右做，左邻已被改成差分，算出的变成二阶差分，全盘皆错

2. **找段起点是下标 2 而非 1**
   - A[1] 是冻结的 $a_1$，卷进排序会破坏端点不变性

3. **判奇偶必须用位运算 `& 1`**
   - C++ 中 `-3 % 2` 得 `-1`，用 `% 2 == 1` 会把负奇数误判为"非奇数"
   - `(x & 1)` 对正负数都正确：奇数得 1，偶数得 0

4. **全程使用 `long long`**
   - 差分绝对值可达 $2 \times 10^9$（超出 `int` 范围）
   - 前缀和累计可达 $10^{14}$ 量级

5. **排序对象是差分，不是原数组**
   - 划分依据是差分的数值奇偶，与符号、大小无关（$-3$ 与 $5$ 同为奇数，$0$ 与 $-8$ 同为偶数）

6. **划分一次即可，不需要迭代重找**
   - 段内元素本来就同奇偶，排序只是段内置换，不改变任何位置上的奇偶，段边界不变

7. **不能在原数组上直接按逐位奇偶贪心**
   - 反例：$a = (0, 1, 4)$，差分 $(1, 3)$ 全奇一段。$a_2$ 只能取 1 或 3，并非任意奇数。真正的约束是"段的多重集"，必须先转差分再分段


### 4. 数学空操作 $\ne$ 代码空操作

有序后若照跑，`idx` 会一路左移出界，`A[idx]` 读到垃圾值再污染 `inv`（WA/RE 的真凶）。卫兵 `if (inv)` 从根上断掉这条路。


## 常见陷阱与注意事项

1. **$-1$ 判定是 $\text{sum}(b) \le 0$ 而非 $< 0$**
   - $\text{sum}(b) = 0$ 时 $a_n = 0$，非正整数，必须输出 $-1$

2. **必须用 `long long`**
   - $b_i$ 可达 $\pm 10^9$，$n$ 可达 $2 \times 10^5$，$\text{sum}(b)$ 可达 $\pm 2 \times 10^{14}$
   - 前缀和同理，中间过程可能远超 `int` 范围

3. **第一步必须是 $\ge 1$ 的正元素**
   - 第一个数 $p_1 = a_1$，落点必须 $\ge 1$
   - 不能把 $0$ 或负数排在最前面——`lower_bound(1 - 0) = lower_bound(1)` 自动跳过它们

4. **阈值是 $1 - s$ 不是 $-s$ 或 $0$**
   - 合法性条件 $s + e \ge 1$，即 $e \ge 1 - s$
   - 不是 $e \ge -s$（那是 $s + e \ge 0$，差一位）

5. **贪的是"落点"最小，不是"增量"最小**
   - 例如 $s = 1$ 时剩余 $\{-5, 2\}$，$e = -5$ 最小但落点是 $-4$，非法，必须选 $2$
   - `lower_bound` 正确处理了这一点：跳过不合法的 $-5$，选 $2$

6. **`lower_bound` 必能找到目标，无需判空**
   - 若找不到，说明所有剩余元素 $< 1 - s \le 0$，全为负数且和 $< 1 - s$
   - 但剩余和 $= T - s \ge 1 - s$（因 $T \ge 1$），矛盾


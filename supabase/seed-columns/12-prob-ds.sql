## 常见陷阱与注意事项

1. **差分方向**：必须从后向前执行 `A[i] -= A[i-1]`。若从前向后，`A[i-1]` 已被修改为差分值而非原值，会导致后续差分全部错误。

2. **数据溢出**：$a_i$ 最大为 $2^{31}$，差分值 $b[i]$ 本身在 `int` 范围内，但 $pos$ 和 $neg$ 是多个差分值的累加，可能超过 `int` 上限。必须使用 `long long` 存储 $pos$ 和 $neg$。

3. **忽略 $b[1]$**：统计 $pos$ 和 $neg$ 时，遍历范围是 $[2, n]$，不包含 $b[1]$。$b[1]$ 是最终公共值，不需要被"归零"。

4. **方案数公式的理解**：方案数为 $|pos - neg| + 1$ 而非 $|pos - neg|$，因为 $k = 0$（不与 $b[1]$ 配对，全部用 $b[n+1]$ 兜底）也是一种合法方案。

5. **虚拟位置 $b[n+1]$ 的作用**：它是一个"垃圾桶"，吸收剩余的正数或负数，不影响最终结果。理解这一点是推导最少次数的关键。


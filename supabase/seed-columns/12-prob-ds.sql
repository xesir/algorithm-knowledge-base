## 解题思路

### 第一步：三个基础观察

**观察 1：两个端点永远不动。** 操作只改写中间位置，$a_1$ 与 $a_n$ 从头到尾不变。$a_1$ 恰好是字典序比较的第一个分量，它已固定，所以目标等价于让 $a_2$ 到 $a_n$ 这一段的字典序尽量小。

**观察 2：每个位置的奇偶性不变。** 合法条件保证 $a_{i-1} + a_{i+1}$ 是偶数，新值 $a_{i-1} - a_i + a_{i+1}$ 与 $-a_i$ 同余，故与旧值同奇偶。但奇偶只是必要条件，不能直接刻画所有可达状态。

**观察 3：操作是自逆的。** 对同一位置连做两次恢复原状。因此只需问"哪些状态彼此连通"，不必关心操作顺序。

### 第二步：核心转化——换到差分数组上看

**为什么想到差分**：操作公式同时牵扯相邻三项，而合法条件比较的却是相距为 2 的两项。"改动一个值、条件看跨位邻居"是差分的典型场景。

设差分 $d_j = a_{j+1} - a_j$，共 $n-1$ 项。给定 $a_1$，原数组与差分一一对应：$a_k = a_1 + \sum_{j=1}^{k-1} d_j$。

**操作在差分上的效果**：一次操作只改 $a_i$。但 $a_i$ 同时是 $d_{i-1}$ 的右端点和 $d_i$ 的左端点，所以 $a_i$ 一变，两个差分都必须重算：

$$d'_{i-1} = a'_i - a_{i-1} = a_{i+1} - a_i = d_i$$
$$d'_i = a_{i+1} - a'_i = a_i - a_{i-1} = d_{i-1}$$

即：**一次操作等价于差分数组上交换相邻的 $d_{i-1}$ 与 $d_i$**。

**合法条件翻译**：$a_{i-1}$ 与 $a_{i+1}$ 同奇偶 $\iff$ $d_{i-1} + d_i$ 为偶 $\iff$ $d_{i-1}$ 与 $d_i$ 同奇偶。

于是问题完全等价于：**每次可以交换差分数组中相邻且奇偶性相同的两项（任意多次），求能得到的最优差分序列。**

### 第三步：可达状态刻画——极大同奇偶连续段

**不变量**：交换双方同奇偶，交换后每个位置上数的奇偶不变，所以差分的"逐位奇偶模式"永不改变。据此把差分切成若干**极大同奇偶连续段**（段内奇偶全同、相邻段奇偶不同）：

- 每段占据的位置集合永远固定（段边界两侧奇偶不同，永远无法交换越界）
- 每段内数字的多重集守恒
- 段内任意相邻两项同奇偶，交换随时合法；相邻交换足以实现段内任意排列（冒泡原理）

**定理**：差分序列 $d'$ 可达，当且仅当它与 $d$ 的奇偶模式相同，且每个极大同奇偶段上的多重集相同。

### 第四步：字典序最小化

**a 的字典序比较 $\iff$ d 的字典序比较**：设两个候选差分的第一个不同位置是 $k$，则两边前 $k-1$ 项前缀和相等，第 $k$ 处前缀和之差恰为 $d_k$ 与 $d'_k$ 之差。

**逐段独立取升序**：各段占据的位置集合固定且互不重叠，互不干扰。固定多重集放到固定位置上，字典序最小的放法是**升序排序**。

**最终结论**：把差分数组按极大同奇偶连续段切开，每段内部升序排序，再用固定的 $a_1$ 逐项累加还原，即为字典序最小的答案。

### 存储约定

本实现不另开差分数组，而是把原数组 A 原地改造成差分，并整体右移一位：

| 阶段 | A[1] | A[2] 到 A[n] |
|---|---|---|
| 读入后 | $a_1$ | 原始 $a$ 值 |
| 原地做差后 | $a_1$（不变） | 相邻差分 |
| 分段排序后 | $a_1$（不变） | 每段升序的差分 |
| 前缀和后 | $a_1$（原样输出） | 答案 $a_2$ 到 $a_n$ |

A[1] 兼任哨兵与种子，A[0] 恒为 0 使做差时第一项无需特判。

## 逐行代码解析

### 原地做差（从右往左）

```cpp
for (int i = n; i >= 1; i--) A[i] -= A[i - 1];
```

**方向是正确性的关键**：算位置 $i$ 的差分时，左邻位置必须还保存着原始 $a_{i-1}$。若从左往右做，左邻已被改成差分，算出的会变成二阶差分。从右往左则保证每个左邻仍是原始值。

### 分段查找与排序

```cpp
for (int i = 2; i <= n;)
{
    int j = i;
    while (j + 1 <= n && ((A[i] & 1) == (A[j + 1] & 1))) j++;
    sort(A.begin() + i, A.begin() + j + 1);
    i = j + 1;
}
```

- **起点是下标 2 而非 1**：A[1] 是冻结的 $a_1$，绝不能卷进排序
- **判奇偶用位运算 `& 1`**：C++ 中负数取模得负，用 `% 2 == 1` 会把两个负奇数误判为不同奇偶
- **用段首元素代表整段奇偶**：段内必然全同，比较段首即可
- 找到段 $[i, j]$ 后直接 `sort` 升序排序


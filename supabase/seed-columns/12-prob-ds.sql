## 二、正序的困难

正序模拟每次切割时，需要：
1. 找到 $k$ 落在哪个宽度段中
2. 删除旧段，插入两个新段
3. 动态维护全局最大值

这需要平衡树或线段树，代码量大且容易出错。

---

## 三、逆序思考：切割变合并

### 3.1 核心转化

| 正序 | 逆序 |
|---|---|
| 切割：一个间隔分成两个 | 撤销：两个相邻间隔合并成一个 |
| 间隔分裂，最大值可能减小 | 间隔合并，最大值只增不减 |

逆序过程中，间隔只会合并，**全局最大间隔单调不减**，因此只需一个变量记录最大值即可，无需任何复杂数据结构维护全局最大。

### 3.2 算法流程

1. 读入所有 $q$ 次操作
2. 收集所有切割坐标，分别加入 $X$ 和 $Y$ 数组（含边界 $0$ 和 $n$/$m$）
3. 排序 $X$ 和 $Y$，得到所有切割都存在时的最终状态
4. 初始化并查集，每个「缝隙」$i$ 对应 $X[i-1]$ 到 $X[i]$，长度为 $X[i] - X[i-1]$
5. 从 $i = q$ 到 $1$ 逆序处理：
   - 先记录答案：$ans[i] = \text{max\_x} \times \text{max\_y}$
   - 撤销第 $i$ 次操作：在对应坐标数组中二分找到切割点下标 $idx$，合并缝隙 $idx$ 和 $idx+1$
   - 更新对应方向的 max
6. 正序输出 $ans[1]$ 到 $ans[q]$


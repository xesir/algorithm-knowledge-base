## 四、高效实现：差分数组

### 4.1 为什么不用暴力？

如果对每个 $y$ 枚举所有 $k$ 检查，时间复杂度 $O(n^2)$，对于 $n=10^5$ 会超时。

### 4.2 差分标记

反过来，对每个 $k$，用差分数组标记它的禁止区间。每个 $k$ 只产生一个区间，总共 $n$ 个区间，差分标记是 $O(1)$ 每个。

```
diff[L] += 1
diff[R + 1] -= 1
```

最后做前缀和，`cur == 0` 的位置就是没被任何禁止区间覆盖的安全元素。

### 4.3 完整算法流程

1. 初始化差分数组 `diff[0..n]` 为 0
2. 对每个 $k = 1$ 到 $n$：
   - $L = a_k \cdot k$，若 $L \ge n$ 则跳过
   - $R = (a_k + 1) \cdot k - 1$，若 $R \ge n$ 则 $R = n - 1$
   - `diff[L]++`，`diff[R+1]--`
3. 前缀和遍历，收集所有 `cur == 0` 的下标作为答案


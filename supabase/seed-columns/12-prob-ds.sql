## 解题思路

### 核心建模：逆序对 = 每个 0 的"账"

01 数组中，逆序对 $=$ 前面的 $1$ 与后面的 $0$ 组成的对。按 $0$ 归账：第 $i$ 个 $0$ 前面有几个 $1$，它就贡献几对。

设 $d_i$ 为第 $i$ 个 $0$ 前面的 $1$ 的个数，则：

$$\text{inv} = \sum_{i=1}^{\text{cnt0}} d_i$$

**建表**：一遍扫描，`cnt1` 遇 $1$ 加一、遇 $0$ 记账（`inv += cnt1; count[cnt1]++; A.push_back(cnt1)`）。

**两条免费性质**（省掉排序和堆）：

1. `cnt1` 只增不减 $\Rightarrow$ $d$ 沿位置非降 $\Rightarrow$ $A[1 \ldots \text{cnt0}]$ 天然有序
2. "当前最大的账"永远是幸存段的最后一根 $A[k]$

### 正向操作（$s_i = 1$）：水位 +1

正向冒泡使最左的 $1$ 一路向右穿过挡道的 $0$。$0$ 在最左 $1$ 右边 $\Leftrightarrow$ 它的 $d \ge 1$。每被穿过一次，那个 $0$ 前面恰好少一个 $1$ $\Rightarrow$ 所有 $d \ge 1$ 的账各减 $1$，$d = 0$ 的不动。

复合 $T$ 次后：$d \to \max(d - T, 0)$，减到 $0$ 封底不为负。

### 反向操作（$s_i = 0$）：删掉最大账

反向冒泡使最右的 $0$ 搬到队首。搬家只挪这一根 $0$，其他元素相对次序不变 $\Rightarrow$ 其他 $0$ 的账不动；搬家这根前面变成没有 $1$，账 $\to 0$。而 $d$ 沿位置非降，最右 $0$ 恰好是账最大的 $\Rightarrow$ 反向 $=$ 删掉当前最大的一笔账。

### 懒标记（水位模型）

逐个减账是每次 $O(n)$。改成记账不记账面：

| 变量 | 含义 |
|------|------|
| `lazy1 = T` | 正向操作总次数 $=$ 水位 |
| `lazy0` | 已拆掉的柱子数（反向操作次数） |
| `A` | 冻结的账本，柱子真实高度 $= \max(A_i - T, 0)$ |
| 幸存柱 | $A[1 \ldots k]$，$k = \text{cnt0} - \text{lazy0}$ |

**总不变式**（一切正确性的核心）：

$$\text{inv} = \sum_{i=1}^{k} \max(A_i - \text{lazy1}, 0)$$

且它等于真实数组的逆序对数。柱子同步沉降（都减同一个 $T$）、拆的又总是最高的，所以幸存者永远是前缀。

**正向**：水位 $+1$；`inv` 减去"涨水前还露在水面上的幸存柱数"（它们各降 $1$）。

**反向**：拆掉 $A[k]$；`inv` 减去它当时的露出高度 $= A[k] - \text{lazy1}$。

### 吸收态：inv = 0（本代码的灵魂）

$\text{inv} = 0$ $\Leftrightarrow$ 全部幸存柱真实高度为 $0$ $\Leftrightarrow$ 数组已排成 $00 \cdots 011 \cdots 1$。

$T$ 只涨、$k$ 只减 $\Rightarrow$ 一旦归零永远为零。有序数组上两种冒泡物理上都是空操作。代码用 `if (inv)` 罩住整个操作处理，归零后全部跳过。

**附赠安全保证**：$\text{inv} > 0$ $\Rightarrow$ 幸存非空 $\Rightarrow$ $\text{idx} \ge 1$，永不越界。

### 新产生的 0 不用记账

正向操作后数组尾部可能新增 $0$（最左 $1$ 冲到队尾变成... 实际上 1 变成在队尾，0 不会新增）。反向操作后队首新增 $0$。① 它账值 $0$，水位只涨，真实值永远 $0$；② 反向删的永远是最大值，账 $0$ 的永远轮不到它。


## 四、「缝隙」与并查集

### 4.1 缝隙定义

以 $x$ 方向为例，排序后的坐标数组 $X = [0, 3, 7, 10]$，缝隙编号从 1 开始：

| 缝隙编号 | 范围 | 长度 |
|---|---|---|
| 1 | $[0, 3]$ | 3 |
| 2 | $[3, 7]$ | 4 |
| 3 | $[7, 10]$ | 3 |

### 4.2 撤销切割 = 合并缝隙

如果切割点 $k$ 在 $X$ 中的下标是 $idx$，那么它左侧缝隙编号是 $idx$，右侧是 $idx+1$。撤销这条切割线就是合并缝隙 $idx$ 和 $idx+1$。

用并查集维护：每个缝隙是一个集合元素，集合的「大小」就是这段缝隙的总长度。合并时长度相加，与新 max 比较更新。

